@dataclass
class KernelBuildError:
    """A structured build error from compiling a kernel."""
    file: str
    line: int
    category: str  # 'missing_constant', 'undefined_symbol', 'link_undefined'
    symbol: str
    context: str


def _parse_build_errors(output: str) -> list[KernelBuildError]:
    """Parse gfortran/linker output into structured build errors."""
    errors = []
    lines = output.split("\n")

    # Track current file context (gfortran prints file:line:col: on one line,
    # the error message on a subsequent line)
    current_file = ""
    current_line = 0

    for i, line in enumerate(lines):
        # File:line:col: context line
        m = re.match(r'^(\S+\.f90):(\d+):\d+:', line, re.IGNORECASE)
        if m:
            current_file = m.group(1)
            current_line = int(m.group(2))
            continue

        stripped = line.strip()

        # "Error: Scalar INTEGER expression expected at (1)"
        # This happens when CHARACTER(IDENTIFIER) uses an undefined constant
        if "Scalar INTEGER expression expected" in stripped:
            # Look backwards for the source line to extract the constant name
            for j in range(i - 1, max(i - 5, -1), -1):
                src_m = re.search(r'CHARACTER\s*\(\s*(?:LEN\s*=\s*)?(\w+)\s*\)',
                                  lines[j], re.IGNORECASE)
                if src_m:
                    errors.append(KernelBuildError(
                        file=current_file, line=current_line,
                        category="missing_constant",
                        symbol=src_m.group(1),
                        context=lines[j].strip(),
                    ))
                    break
            continue

        # "Error: Symbol 'xxx' at (1) has no IMPLICIT type"
        # gfortran uses Unicode curly quotes (\u2018 \u2019) not ASCII quotes
        m = re.match(r"Error:\s+Symbol\s+['\u2018](\w+)['\u2019]\s+at\s+\(1\)\s+has no IMPLICIT type",
                     stripped, re.IGNORECASE)
        if m:
            errors.append(KernelBuildError(
                file=current_file, line=current_line,
                category="undefined_symbol",
                symbol=m.group(1),
                context=stripped,
            ))
            continue

        # "undefined reference to 'symbol_'" (linker)
        # Linker may use backtick, ASCII quote, or Unicode curly quotes
        m = re.search(r"undefined reference to [`'\u2018](\w+)['\u2019]", stripped)
        if m:
            errors.append(KernelBuildError(
                file=current_file, line=0,
                category="link_undefined",
                symbol=m.group(1),
                context=stripped,
            ))
            continue

    # Deduplicate by (category, symbol)
    seen = set()
    unique = []
    for e in errors:
        key = (e.category, e.symbol.lower())
        if key not in seen:
            seen.add(key)
            unique.append(e)
    return unique


def _resolve_character_star_lengths(
    kernel_content: str, source_dir: Optional[str]
) -> dict:
    """Resolve actual lengths for each CHARACTER(LEN=*) variable in a kernel.

    Returns dict mapping lowercase variable name → integer length.
    For each variable, traces: kernel local → enclosing function parameter →
    caller's actual argument → resolved constant from source tree.
    """
    result = {}
    default = 4096

    if not source_dir:
        return result

    # Collect all CHARACTER(LEN=*) variable names (non-INTENT, i.e., locals)
    star_vars = []
    for m in re.finditer(
        r'^[^!]*CHARACTER\s*\(.*\*.*\)\s*::\s*(\w+)',
        kernel_content, re.MULTILINE | re.IGNORECASE,
    ):
        line = m.group(0)
        if re.search(r'INTENT', line, re.IGNORECASE):
            continue
        star_vars.append(m.group(1).lower())

    if not star_vars:
        return result

    # Find the enclosing function name from CALL <func>(kgen_unit, kgen_measure, ...)
    call_m = re.search(
        r'CALL\s+(\w+)\s*\(\s*kgen_unit\s*,\s*kgen_measure',
        kernel_content, re.IGNORECASE,
    )
    if not call_m:
        return result
    enclosing_name = call_m.group(1)

    # Find the enclosing function's signature in the source tree
    from .fortran_parser import find_function_in_file
    source_path = Path(source_dir)
    enclosing_sig = None
    for f90 in sorted(source_path.rglob("*.[fF]90")):
        try:
            enclosing_sig = find_function_in_file(str(f90), enclosing_name)
            break
        except (ValueError, FileNotFoundError):
            continue

    if not enclosing_sig:
        return result

    # Build map: enclosing function's CHARACTER parameter name → position index
    char_params = {}
    for idx, arg in enumerate(enclosing_sig.args):
        if arg.fortran_type.upper().startswith("CHARACTER"):
            char_params[arg.name.lower()] = (idx, arg.fortran_type)

    # For each kernel variable, find the matching enclosing parameter
    def _resolve_len_spec(len_spec: str) -> Optional[int]:
        """Resolve a CHARACTER length specifier to an integer."""
        try:
            return int(len_spec)
        except ValueError:
            pass
        search_dir = Path(source_dir)
        while search_dir != search_dir.parent:
            val = _find_constant_in_source(len_spec, str(search_dir))
            if val is not None:
                return val
            search_dir = search_dir.parent
        return None

    for var_name in star_vars:
        # Match kernel variable to enclosing function parameter by name
        # (kernel variables are named after the function parameters, possibly
        # with kgenref_ prefix)
        base_name = var_name.replace("kgenref_", "")
        if base_name not in char_params:
            continue
        _, fortran_type = char_params[base_name]

        # Try to resolve directly from the parameter declaration
        len_m = re.search(
            r'CHARACTER\s*\(\s*(?:LEN\s*=\s*)?(\w+)\s*\)',
            fortran_type, re.IGNORECASE,
        )
        if len_m and len_m.group(1) != '*':
            resolved = _resolve_len_spec(len_m.group(1))
            if resolved is not None:
                result[var_name] = resolved
                continue

        # Parameter is CHARACTER(*) — find callers and trace the actual argument
        param_idx = char_params[base_name][0]
        call_re = re.compile(
            rf'CALL\s+{re.escape(enclosing_name)}\s*\(([^)]*)\)',
            re.IGNORECASE,
        )
        resolved_from_caller = None
        for f90 in sorted(source_path.rglob("*.[fF]90")):
            if resolved_from_caller is not None:
                break
            try:
                src = f90.read_text()
            except (UnicodeDecodeError, PermissionError):
                continue
            for cm in call_re.finditer(src):
                args_str = cm.group(1)
                args = [a.strip() for a in args_str.split(",")]
                if param_idx >= len(args):
                    continue
                actual_arg = args[param_idx]
                # Find this argument's CHARACTER declaration in the same file
                decl_re = re.compile(
                    rf'CHARACTER\s*\(\s*(?:LEN\s*=\s*)?([A-Za-z_]\w*)\s*\)'
                    rf'[^:]*::[^!]*\b{re.escape(actual_arg)}\b',
                    re.IGNORECASE,
                )
                dm = decl_re.search(src)
                if dm:
                    resolved_from_caller = _resolve_len_spec(dm.group(1))
                    if resolved_from_caller is not None:
                        break
        if resolved_from_caller is not None:
            result[var_name] = resolved_from_caller

    return result


def _find_constant_in_source(symbol: str, source_dir: str) -> Optional[int]:
    """Search project source for an INTEGER PARAMETER definition and return its value."""
    pattern = re.compile(
        rf'INTEGER\b[^:]*PARAMETER[^:]*::\s*{re.escape(symbol)}\s*=\s*(\d+)',
        re.IGNORECASE,
    )
    source_path = Path(source_dir)
    for fpath in sorted(source_path.rglob("*.[fF]90")):
        try:
            content = fpath.read_text()
        except (UnicodeDecodeError, PermissionError):
            continue
        m = pattern.search(content)
        if m:
            return int(m.group(1))
    return None


def _fix_missing_constant(
    kernel: Path, error: KernelBuildError, source_dir: str
) -> bool:
    """Fix a missing constant by inlining its value from project source.

    Replaces CHARACTER(CONST) and CHARACTER(LEN=CONST) with CHARACTER(value).
    Also adds a dummy INTEGER declaration if the constant is READ from state data.

    Returns True if a fix was applied.
    """
    value = _find_constant_in_source(error.symbol, source_dir)
    if value is None:
        return False

    target = kernel / error.file
    if not target.exists():
        return False

    content = target.read_text()
    original = content
    name = error.symbol

    content = re.sub(
        rf'CHARACTER\s*\(\s*{name}\s*\)',
        f'CHARACTER({value})',
        content, flags=re.IGNORECASE,
    )
    content = re.sub(
        rf'CHARACTER\s*\(\s*LEN\s*=\s*{name}\s*\)',
        f'CHARACTER(LEN={value})',
        content, flags=re.IGNORECASE,
    )

    if content != original:
        target.write_text(content)
        return True
    return False


def _fix_undefined_symbol(
    kernel: Path, error: KernelBuildError, source_dir: str
) -> bool:
    """Fix an undefined symbol by adding its declaration.

    For symbols that are READ from KGen state data (like errmsglen),
    adds a local INTEGER declaration so the sequential binary read succeeds.
    For symbols defined as PARAMETERs in project source, inlines the value.

    Returns True if a fix was applied.
    """
    symbol = error.symbol
    target = kernel / error.file
    if not target.exists():
        return False

    content = target.read_text()

    # Check if this symbol is READ from state data in this file
    if re.search(rf'READ\s*\([^)]*\)\s*{symbol}\b', content, re.IGNORECASE):
        # Add local INTEGER declaration
        if not re.search(rf'INTEGER\b[^:]*::\s*{symbol}\b', content, re.IGNORECASE):
            lines = content.split("\n")
            # Insert after first IMPLICIT NONE, or after last USE, or at top
            insert_idx = None
            for i, line in enumerate(lines):
                stripped = line.strip().upper()
                if stripped.startswith("IMPLICIT NONE"):
                    insert_idx = i + 1
                    break
            if insert_idx is None:
                for i, line in enumerate(lines):
                    if re.match(r'\s*USE\s+', line.strip(), re.IGNORECASE):
                        insert_idx = i + 1
            if insert_idx is not None:
                lines.insert(insert_idx,
                    f"    INTEGER :: {symbol}  ! VIT: dummy for sequential binary state read")
                target.write_text("\n".join(lines))
                return True

    # Check if it's a PARAMETER in the project source — inline it
    value = _find_constant_in_source(symbol, source_dir)
    if value is not None:
        if re.search(rf'PARAMETER\s*::\s*{symbol}\b', content, re.IGNORECASE):
            return False
        lines = content.split("\n")
        insert_idx = None
        for i, line in enumerate(lines):
            stripped = line.strip().upper()
            if stripped.startswith("IMPLICIT NONE"):
                insert_idx = i + 1
                break
        if insert_idx is None:
            for i, line in enumerate(lines):
                if re.match(r'\s*USE\s+', line.strip(), re.IGNORECASE):
                    insert_idx = i + 1
        if insert_idx is not None:
            lines.insert(insert_idx,
                f"    INTEGER, PARAMETER :: {symbol} = {value}  ! VIT: from project source")
            target.write_text("\n".join(lines))
            return True

    return False


def _fix_link_undefined(
    kernel: Path, error: KernelBuildError, source_dir: str = ""
) -> bool:
    """Fix an undefined linker symbol.

    Strategy 1: Detect LAPACK/BLAS symbols by naming convention → add -l flags.
    Strategy 2: Find the Fortran subroutine in the project source → inject into
                the kernel module that should contain it.

    Returns True if a fix was applied.
    """
    symbol = error.symbol.rstrip("_")  # Remove Fortran name mangling underscore

    # Strategy 1: Standard LAPACK/BLAS naming
    is_lapack_blas = bool(re.match(
        r'^[sdcz]'
        r'(?:ge[a-z]{2,4}|gb[a-z]{2,4}|gt[a-z]{2,4}|'
        r'po[a-z]{2,4}|pp[a-z]{2,4}|pb[a-z]{2,4}|pt[a-z]{2,4}|'
        r'sy[a-z]{2,4}|sp[a-z]{2,4}|he[a-z]{2,4}|hp[a-z]{2,4}|'
        r'or[a-z]{2,4}|un[a-z]{2,4}|tr[a-z]{2,4}|tp[a-z]{2,4}|'
        r'tb[a-z]{2,4}|st[a-z]{2,4}|bd[a-z]{2,4}|la[a-z]{2,4}|'
        r'axpy|scal|copy|dot|nrm2|gemm|gemv|trsm|trsv)$',
        symbol.lower(),
    ))

    if is_lapack_blas:
        makefile = kernel / "Makefile"
        if not makefile.exists():
            return False
        content = makefile.read_text()
        if "-llapack" in content:
            return False
        lines = content.split("\n")
        for i, line in enumerate(lines):
            if ("-o kernel.exe" in line or "-o\tkernel.exe" in line) \
                    and "rm " not in line and "./" not in line:
                lines[i] = line.rstrip() + " -llapack -lblas"
                makefile.write_text("\n".join(lines))
                return True
        return False

    # Strategy 2: Find subroutine in project source and inject into kernel module
    if not source_dir:
        return False

    # Search project source for SUBROUTINE/FUNCTION definition
    sub_pattern = re.compile(
        rf'^\s*((?:PURE\s+|ELEMENTAL\s+|RECURSIVE\s+)*'
        rf'(?:SUBROUTINE|FUNCTION)\s+{re.escape(symbol)}\s*\()',
        re.IGNORECASE | re.MULTILINE,
    )
    end_pattern = re.compile(
        rf'^\s*END\s+(?:SUBROUTINE|FUNCTION)(?:\s+{re.escape(symbol)})?\s*$',
        re.IGNORECASE | re.MULTILINE,
    )

    source_path = Path(source_dir)
    for fpath in sorted(source_path.rglob("*.[fF]90")):
        try:
            content = fpath.read_text()
        except (UnicodeDecodeError, PermissionError):
            continue

        start_match = sub_pattern.search(content)
        if not start_match:
            continue
        end_match = end_pattern.search(content, start_match.start())
        if not end_match:
            continue

        # Extract the subroutine body
        sub_body = content[start_match.start():end_match.end()]

        # Find which module this subroutine belongs to
        # Look backwards from the subroutine start for MODULE name
        before_sub = content[:start_match.start()]
        module_name = None
        for m in re.finditer(r'MODULE\s+(\w+)\s*$', before_sub, re.IGNORECASE | re.MULTILINE):
            name = m.group(1)
            if name.upper() not in ("PROCEDURE", "FUNCTION", "SUBROUTINE"):
                module_name = name

        if not module_name:
            continue

        # Find the kernel file that defines this module
        target_file = None
        for kf in sorted(kernel.glob("*.[fF]90")):
            kc = kf.read_text()
            if re.search(rf'MODULE\s+{module_name}\s*$', kc, re.IGNORECASE | re.MULTILINE):
                target_file = kf
                break

        if not target_file:
            continue

        # Inject the subroutine before END MODULE
        tc = target_file.read_text()
        end_mod = re.search(rf'END\s+MODULE\s+{module_name}', tc, re.IGNORECASE)
        if not end_mod:
            continue

        # Check if subroutine already exists
        if re.search(rf'SUBROUTINE\s+{re.escape(symbol)}\s*\(', tc, re.IGNORECASE):
            continue

        # Ensure CONTAINS exists
        if "CONTAINS" not in tc.upper().split("END MODULE")[0]:
            insert_pos = end_mod.start()
            tc = tc[:insert_pos] + "\nCONTAINS\n\n" + sub_body + "\n\n" + tc[insert_pos:]
        else:
            insert_pos = end_mod.start()
            tc = tc[:insert_pos] + "\n" + sub_body + "\n\n" + tc[insert_pos:]

        target_file.write_text(tc)
        return True

    return False


def _repair_kernel_build(
    kernel: Path,
    source_dir: str,
    fortran_compiler: str,
    env: dict,
) -> dict:
    """Compile-error-driven kernel repair loop.

    Attempts to build the kernel, parses compiler/linker errors, applies
    fixes from the project source tree, and retries. Terminates when the
    build succeeds or no more fixes can be applied (all fix functions are
    idempotent, so the loop always converges).

    Returns:
        dict with 'success' (bool), 'modified' (list of files), 'errors' (list),
        'iterations' (int), 'log' (list of human-readable repair descriptions)
    """
    result = {
        "success": False,
        "modified": [],
        "errors": [],
        "iterations": 0,
        "log": [],
    }

    max_iterations = 100
    iteration = 0
    while iteration < max_iterations:
        iteration += 1
        result["iterations"] = iteration

        # Clean and build (merge stderr into stdout for coherent error parsing)
        subprocess.run("make clean", shell=True, cwd=str(kernel),
                       capture_output=True, env=env)
        build = subprocess.run(
            "make build 2>&1", shell=True, cwd=str(kernel),
            capture_output=True, text=True, env=env,
        )

        if build.returncode == 0:
            result["success"] = True
            result["log"].append(f"Build succeeded on iteration {iteration}")
            return result

        # Parse errors
        output = build.stdout
        errors = _parse_build_errors(output)

        if not errors:
            result["errors"].append(
                f"Build failed but no parseable errors found. Output:\n{output[-2000:]}"
            )
            return result

        # Try to fix each error
        fixes_applied = 0
        for error in errors:
            fixed = False
            if error.category == "missing_constant":
                fixed = _fix_missing_constant(kernel, error, source_dir)
            elif error.category == "undefined_symbol":
                fixed = _fix_undefined_symbol(kernel, error, source_dir)
            elif error.category == "link_undefined":
                fixed = _fix_link_undefined(kernel, error, source_dir)

            if fixed:
                fixes_applied += 1
                result["modified"].append(error.file)
                result["log"].append(
                    f"[iter {iteration}] Fixed {error.category}: "
                    f"{error.symbol} in {error.file}"
                )

        if fixes_applied == 0:
            result["errors"].append(
                f"Build failed with {len(errors)} errors, none fixable automatically. "
                f"First unfixed: {errors[0].category} '{errors[0].symbol}' in {errors[0].file}"
            )
            return result

    result["errors"].append(f"Reached safety limit ({max_iterations} iterations)")
    return result


def _fix_use_ordering(content: str) -> str:
    """
    Ensure USE statements come before IMPLICIT NONE.

    This is a Fortran syntax requirement. USE statements must appear
    before IMPLICIT NONE in the same scoping unit.
    """
    lines = content.split("\n")
    i = 0
    while i < len(lines):
        line_upper = lines[i].strip().upper()

        # If we find IMPLICIT NONE, check if subsequent USE statements
        # need to be moved before it
        if line_upper.startswith("IMPLICIT NONE") or line_upper == "IMPLICIT NONE":
            j = i + 1
            use_lines_to_move = []
            while j < len(lines):
                next_upper = lines[j].strip().upper()
                if next_upper.startswith("USE "):
                    use_lines_to_move.append(lines[j])
                    lines.pop(j)
                elif not next_upper or next_upper.startswith("!"):
                    j += 1  # Skip blank lines and comments
                else:
                    break

            # Insert USE lines before IMPLICIT NONE
            for k, use_line in enumerate(use_lines_to_move):
                lines.insert(i + k, use_line)
            i += len(use_lines_to_move)

        i += 1

    return "\n".join(lines)


def _add_use_iso_c_binding(content: str) -> str:
    """Add USE ISO_C_BINDING at module level, before first IMPLICIT NONE."""
    lines = content.split("\n")
    for i, line in enumerate(lines):
        stripped = line.strip().upper()
        if stripped.startswith("IMPLICIT NONE") or stripped == "IMPLICIT NONE":
            indent = len(line) - len(line.lstrip())
            lines.insert(i, " " * indent + "USE ISO_C_BINDING")
            break
    return "\n".join(lines)


def _add_interface_block(content: str, interface_block: str) -> str:
    """Add INTERFACE block above the CONTAINS statement."""
    lines = content.split("\n")

    # Find CONTAINS
    for i, line in enumerate(lines):
        if line.strip().upper() == "CONTAINS":
            lines.insert(i, "")
            lines.insert(i, interface_block)
            lines.insert(i, "")
            return "\n".join(lines)

    # No CONTAINS found — add before END MODULE
    for i in range(len(lines) - 1, -1, -1):
        if re.match(r'\s*END\s+MODULE', lines[i], re.IGNORECASE):
            lines.insert(i, "")
            lines.insert(i, "CONTAINS")
            lines.insert(i, "")
            lines.insert(i, interface_block)
            lines.insert(i, "")
            return "\n".join(lines)

    # Fallback: append
    lines.append("")
    lines.append(interface_block)
    return "\n".join(lines)


def _replace_function_body(content: str, sig: FortranSignature,
                           wrapper_body: str) -> str:
    """
    Replace the original function body with the C-calling wrapper.

    Finds the function definition and replaces it entirely.
    """
    lines = content.split("\n")
    name_upper = sig.name.upper()
    end_keyword = "FUNCTION" if sig.is_function else "SUBROUTINE"

    # Find function start
    start_idx = None
    for i, line in enumerate(lines):
        stripped = line.strip().upper()
        if re.search(rf'\b{end_keyword}\s+{name_upper}\s*\(', stripped):
            if not stripped.startswith("END"):
                start_idx = i
                break

    if start_idx is None:
        return content

    # Find function end
    end_idx = None
    for i in range(start_idx, len(lines)):
        stripped = lines[i].strip().upper()
        if re.match(rf'\s*END\s+{end_keyword}\b', stripped):
            end_idx = i
            break

    if end_idx is None:
        return content

    # Replace the function body (start to end inclusive) with wrapper
    new_lines = lines[:start_idx] + wrapper_body.split("\n") + lines[end_idx + 1:]
    return "\n".join(new_lines)


def _parse_verify_output(output: str, tolerance: float) -> VerifyResult:
    """
    Parse KGen kernel verification output.

    KGen output has per-case blocks like:

        ***************** Verification against 'saturate.0.0.1' *****************
        localvar%istatus is IDENTICAL.
        ...
        Verification PASSED with saturate.0.0.1

    Or for cases with NaN reference data (invalid state capture):

        ***************** Verification against 'saturate.0.0.3' *****************
        Difference is                        NaN
        ...
        Verification FAILED withsaturate.0.0.3

    And a summary block:
        Total number of verification cases  :     1
        Number of verification-passed cases :     1

    Cases where all differences are NaN indicate corrupted reference data
    from KGen's state capture (e.g., initialization calls with uninitialized
    struct fields). These are classified as "skipped" rather than "failed".
    """
    per_case_total = 0
    per_case_passed = 0
    per_case_failed = 0
    per_case_skipped = 0
    summary_total = None
    summary_passed = None
    max_error = 0.0
    details = []
    field_data = []

    # Track NaN differences within each case block.
    # When we see a case header (*** Verification against ***), reset the flag.
    # When we see "Difference is NaN", set it.
    # When we see FAILED, check if NaN was present → classify as skipped.
    current_case_has_nan = False
    current_case_name = ""

    # KGen reports how many variables it actually compared. A kernel whose
    # callsite result never lands in a captured variable -- CurTime(), whose
    # value goes straight into a WRITE -- compares ZERO and still prints
    # "Verification PASSED". Without this the pass is vacuous and reads exactly
    # like a real one.
    # None means KGen never printed the line at all, which is not the same as
    # printing zero -- only an explicit zero is evidence that nothing was
    # compared.
    output_vars_seen = None

    for line in output.split("\n"):
        line_stripped = line.strip()
        line_upper = line_stripped.upper()

        # Detect case header — reset NaN tracking, capture case name
        case_match = re.search(r"Verification against '([^']+)'", line, re.IGNORECASE)
        if case_match:
            current_case_name = case_match.group(1)
            current_case_has_nan = False
            continue

        # Parse field value logging lines
        if "[VIT_FIELD]" in line:
            rest = line[line.index("[VIT_FIELD]") + len("[VIT_FIELD]"):].strip()
            parts = [p.strip() for p in rest.split("|")]
            if len(parts) >= 3:
                entry = {
                    "case": current_case_name,
                    "field": parts[0],
                    "type": "scalar",
                    "status": parts[1],
                    "computed": parts[2] if len(parts) > 2 else "",
                    "reference": parts[3] if len(parts) > 3 else "",
                    "diff": parts[4] if len(parts) > 4 else "",
                }
                field_data.append(entry)
            continue

        if "[VIT_ARRAY]" in line:
            rest = line[line.index("[VIT_ARRAY]") + len("[VIT_ARRAY]"):].strip()
            parts = [p.strip() for p in rest.split("|")]
            if len(parts) >= 2:
                entry = {
                    "case": current_case_name,
                    "field": parts[0],
                    "type": "array",
                    "status": parts[1],
                    "computed": "",
                    "reference": "",
                    "diff": "",
                }
                # Extract array-specific info from remaining parts
                for p in parts[2:]:
                    entry["diff"] += p.strip() + " "
                entry["diff"] = entry["diff"].strip()
                field_data.append(entry)
            continue

        # Detect NaN differences within a case block
        if re.search(r'Difference\s+is\s+NaN', line, re.IGNORECASE):
            current_case_has_nan = True
            continue

        # Parse summary lines (these are authoritative for total/passed counts)
        total_match = re.search(
            r'Total number of verification cases\s*:\s*(\d+)', line)
        if total_match:
            summary_total = int(total_match.group(1))
            continue

        passed_match = re.search(
            r'Number of verification-passed cases\s*:\s*(\d+)', line)
        if passed_match:
            summary_passed = int(passed_match.group(1))
            continue

        outvars_match = re.search(
            r'Number of output variables\s*:\s*(\d+)', line, re.IGNORECASE)
        if outvars_match:
            output_vars_seen = (output_vars_seen or 0) + int(outvars_match.group(1))
            continue

        # Skip summary/count lines — don't count them as per-case results
        if re.search(r'Number of\s+(non-)?identical', line, re.IGNORECASE):
            continue

        # Per-case results: "Verification PASSED with <name>"
        if re.search(r'Verification\s+PASSED\s+with\b', line, re.IGNORECASE):
            per_case_total += 1
            per_case_passed += 1
            details.append({"status": "PASSED", "line": line_stripped})
            current_case_has_nan = False

        elif re.search(r'Verification\s+FAILED', line, re.IGNORECASE):
            per_case_total += 1
            if current_case_has_nan:
                # NaN reference data — invalid state capture, not a real failure
                per_case_skipped += 1
                details.append({
                    "status": "SKIPPED",
                    "line": line_stripped,
                    "reason": "NaN reference data (invalid state capture)",
                })
            else:
                per_case_failed += 1
                details.append({"status": "FAILED", "line": line_stripped})

                err_match = re.search(
                    r'error\s*[:=]\s*([\d.eE+-]+)', line, re.IGNORECASE)
                if err_match:
                    try:
                        max_error = max(max_error, float(err_match.group(1)))
                    except ValueError:
                        pass
            current_case_has_nan = False

        elif re.search(r'PASSED\s+verification\b', line, re.IGNORECASE):
            # "kernel: saturate: PASSED verification" — this is a summary echo
            # Don't double-count if we already have per-case data
            if per_case_total == 0:
                per_case_total += 1
                per_case_passed += 1
                details.append({"status": "PASSED", "line": line_stripped})

        elif re.search(r'FAILED\s+verification\b', line, re.IGNORECASE):
            if per_case_total == 0:
                per_case_total += 1
                per_case_failed += 1
                details.append({"status": "FAILED", "line": line_stripped})

    # Compute final counts.
    # KGen's summary counts include NaN cases as failures. We need to
    # adjust: real failures = summary failures - skipped NaN cases.
    if summary_total is not None and summary_passed is not None:
        total = summary_total
        passed = summary_passed
        skipped = per_case_skipped
        failed = total - passed - skipped
    else:
        total = per_case_total
        passed = per_case_passed
        skipped = per_case_skipped
        failed = per_case_failed

    # Success means: at least one valid case, and no real failures.
    # NaN-skipped cases don't count against success.
    valid_cases = total - skipped
    success = valid_cases > 0 and failed == 0

    # A kernel that compared no variables has verified nothing, whatever it
    # printed. Report it as a failure rather than a pass: the alternative is a
    # green result that means the opposite of what it appears to.
    #
    # This is not the same as "no cases captured" (which extraction already
    # reports). Here the cases exist and were replayed -- there was simply
    # nothing to compare them on, because the function's result never reaches a
    # variable KGen captures.
    if success and output_vars_seen == 0:  # explicit zero, not a missing line
        success = False
        details.append({
            "status": "FAILED",
            "line": "kernel compared 0 output variables — nothing was verified",
            "reason": (
                "The call site's result does not land in a variable KGen "
                "captures (e.g. it is consumed directly by a WRITE). Kernel "
                "replay cannot verify this function; use vit test-validate."
            ),
        })

    return VerifyResult(
        success=success,
        total_cases=total,
        passed_cases=passed,
        failed_cases=failed,
        skipped_cases=skipped,
        max_error=max_error,
        output=output,
        details=details,
        field_data=field_data,
    )