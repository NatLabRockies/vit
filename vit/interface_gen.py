def _bridge_char_args(sig, kind_aliases, derived_types):
    """CHARACTER arguments of a kernel callee bridge, with bridge-side sizes.

    The bridge receives what C sends -- a flat CHARACTER(KIND=C_CHAR) array of
    bytes -- and the Fortran callee wants a CHARACTER(*) scalar or array. Those
    are not the same thing: passing the C_CHAR array straight through is a rank
    mismatch on a scalar dummy, and on an array dummy it would silently reshape
    the element boundaries.

    So each CHARACTER argument is staged through a local of the callee's own
    shape. The sizes are the ones the BRIDGE has, not the ones the forward
    wrapper has: `len_<name>` (a dummy of this bridge) rather than
    `LEN(<name>)`, which would be the length of the C_CHAR array, and `n_<name>`
    rather than `SIZE(<name>)`, which is not defined for an assumed-size dummy.

    Returns (arg, len_expr, count_expr_or_None).
    """
    out = []
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        if not mapping.iso_c_type.startswith("CHARACTER"):
            continue
        if mapping.character_len_param == "*":
            len_expr = f"len_{arg.name}"
        else:
            len_expr = _get_char_len_expr(arg, mapping, sig)
        if not len_expr:
            continue
        count = None
        if getattr(arg, "is_array", False):
            if getattr(arg, "is_assumed_shape", False) or not arg.array_dims:
                count = f"n_{arg.name}"
            else:
                count = _char_array_count_expr(arg)
        out.append((arg, len_expr, count))
    return out


def _bridge_char_copies_back(arg):
    """Copy a staged CHARACTER local back to C? Yes unless it is INTENT(IN).

    An argument with no declared intent is assumed to be modifiable. Copying
    back something the callee did not touch is a no-op -- the local was seeded
    from the same bytes -- while skipping a copy-back the callee did need is a
    silent wrong answer.
    """
    return not (arg.intent and arg.intent.value.upper() == "IN")


def generate_kernel_callee_bridge(
    sig: FortranSignature,
    kind_aliases: Optional[dict] = None,
    derived_types: Optional[dict] = None,
) -> str:
    """
    Generate a Fortran BIND(C) bridge that calls the original Fortran function.

    This is the inverse of generate_fortran_wrapper(): instead of Fortran→C,
    it wraps C→Fortran. Used in the KGen kernel to allow C++ translations
    to call functions that remain as original Fortran in the kernel context.

    The bridge:
    1. Has BIND(C, NAME='callee_c') so C++ can call it
    2. Accepts C-compatible types (same as the BIND(C) interface)
    3. Converts C types back to Fortran types where needed
    4. Calls the original Fortran function
    5. Returns the result as a C type

    Args:
        sig: Parsed signature of the callee function
        kind_aliases: Project-specific kind aliases
        derived_types: Registry of known derived types

    Returns:
        Complete Fortran source for the bridge function
    """

    # CHARACTER-valued results are supported in the forward direction (the
    # translated function returns through an output buffer) but NOT here. A
    # bridge would have to stage the Fortran CHARACTER result into a C_CHAR
    # array and blank-pad it, and none of the code below does that. Fail loudly
    # rather than emit a bridge that compiles and truncates.
    if result_char_len(sig, kind_aliases, derived_types):
        raise NotImplementedError(
            f"Callee bridge for '{sig.name}' returns CHARACTER, which is not yet "
            f"supported. Translate the callee first, or extend "
            f"generate_kernel_callee_bridge() to stage the result buffer."
        )
    lines = []
    c_func_name = sig.c_func_name
    bridge_name = f"{sig.name.lower()}_bridge"

    lines.append(f"! VIT: Kernel callee bridge for {sig.name}")
    lines.append(f"! Allows C++ translations to call the original Fortran function.")

    # Build the BIND(C) interface args (same as what the C++ side expects)
    iface_args = _build_interface_args(sig, kind_aliases, derived_types)

    # Collect USE statements for derived types
    use_stmts = _get_use_statements_for_derived_types(sig)

    # Identify struct pointer args that need C_F_POINTER conversion.
    # View-type args are handled differently — they use a module stash variable
    # instead of C_F_POINTER (the view struct has a different memory layout).
    struct_args = []
    view_struct_args = []
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        if mapping.is_derived and mapping.is_c_compatible and not arg.is_optional:
            if mapping.is_view_type:
                view_struct_args.append((arg, mapping))
            else:
                struct_args.append((arg, mapping))

    # Fall back to registry source_module for struct args whose types weren't
    # found in the function's own USE statements (module procedures inherit
    # USE from the parent module, so their own use_statements may be empty).
    if derived_types and struct_args:
        covered = {t.upper() for stmt in use_stmts for t in
                   [a.derived_type_name for a in sig.args if a.is_derived_type]
                   if t.upper() in stmt.upper()}
        for arg, mapping in struct_args:
            t_upper = arg.derived_type_name.upper()
            if t_upper not in covered:
                for k, v in derived_types.items():
                    if k.upper() == t_upper and v.source_module:
                        use_stmts.append(
                            f"USE {v.source_module}, ONLY: {arg.derived_type_name}")
                        break

    # For array-returning functions, identify the result buffer and size params.
    # The result buffer parameter is already added by _build_interface_args (line 848+).
    result_buffer_name = None
    result_size_param = None
    if sig.is_function and sig.result_is_array:
        result_buffer_name = f"{sig.name}_result"
        # Use first array arg's size as result size (VIT convention)
        for a in sig.args:
            if a.is_array and a.is_assumed_shape:
                result_size_param = f"n_{a.name}"
                break

    if sig.is_function and not result_is_out_param(sig, kind_aliases, derived_types):
        # Scalar-returning function
        ret_mapping = _get_return_type_mapping(sig, kind_aliases, derived_types)
        result_name = "bridge_result"

        lines.append(f"    FUNCTION {bridge_name}({', '.join(a['iface_name'] for a in iface_args)}) &")
        lines.append(f"        BIND(C, NAME='{c_func_name}') RESULT({result_name})")
    else:
        # Subroutine (or array-valued function treated as subroutine)
        lines.append(f"    SUBROUTINE {bridge_name}({', '.join(a['iface_name'] for a in iface_args)}) &")
        lines.append(f"        BIND(C, NAME='{c_func_name}')")

    lines.append(f"        USE ISO_C_BINDING")
    # USE the module that defines the callee so we can call it
    if sig.module_name:
        lines.append(f"        USE {sig.module_name}, ONLY: {sig.name}")
    for use_stmt in dict.fromkeys(use_stmts):
        lines.append(f"        {use_stmt}")
    # USE view stash modules for view-type args (bridges use the stash instead of C_F_POINTER).
    # For INOUT/OUT view args, also import the populator + view type for post-call re-sync
    # (Fortran may modify scalars in the original type; the view must reflect those changes
    # so the caller's reverse-copy doesn't overwrite them with stale values).
    for arg, mapping in view_struct_args:
        type_lower = mapping.c_type.lower()
        module_name = f"vit_{type_lower}_view"
        stash_name = f"vit_original_{type_lower}"
        needs_resync = arg.intent and arg.intent.value.upper() in ("INOUT", "OUT")
        if needs_resync:
            view_type = f"{type_lower}_view_t"
            populator = f"vit_populate_{type_lower}"
            reverse_copy = f"vit_copy_scalars_to_{type_lower}"
            lines.append(f"        USE {module_name}, ONLY: {stash_name}, {view_type}, {populator}, {reverse_copy}")
        else:
            lines.append(f"        USE {module_name}, ONLY: {stash_name}")
    lines.append(f"        IMPLICIT NONE")

    # Declare BIND(C) arguments (same as interface block)
    for a in iface_args:
        lines.append(f"        {a['iface_decl']}")

    # Declare result for functions
    if sig.is_function and not result_is_out_param(sig, kind_aliases, derived_types):
        lines.append(f"        {ret_mapping.iso_c_type} :: {result_name}")

    # Declare local Fortran pointer variables for regular struct args (not view types)
    for arg, mapping in struct_args:
        if arg.is_array:
            lines.append(f"        TYPE({arg.derived_type_name}), POINTER :: {arg.name}_f(:)")
        else:
            lines.append(f"        TYPE({arg.derived_type_name}), POINTER :: {arg.name}_f")
    # Declare local view pointers for post-call re-sync (INOUT/OUT only)
    for arg, mapping in view_struct_args:
        if arg.intent and arg.intent.value.upper() in ("INOUT", "OUT"):
            type_lower = mapping.c_type.lower()
            lines.append(f"        TYPE({type_lower}_view_t), POINTER :: {arg.name}_view")

    # Stage every CHARACTER argument through a local of the callee's own shape.
    # These are automatic objects: their length and extent come from this
    # bridge's own dummies, which is legal and is what makes an arbitrary
    # caller-supplied length work.
    char_stage_args = _bridge_char_args(sig, kind_aliases, derived_types)
    for arg, len_expr, count in char_stage_args:
        dims = f"({count})" if count else ""
        lines.append(f"        CHARACTER({len_expr}) :: local_{arg.name}{dims}")
        if count:
            lines.append(f"        INTEGER :: vit_i_{arg.name}, vit_j_{arg.name}")
        else:
            lines.append(f"        INTEGER :: vit_i_{arg.name}")

    # Convert C struct pointers to Fortran pointers (regular structs only)
    if struct_args:
        lines.append(f"        ! Convert C pointers to Fortran pointers")
    for arg, mapping in struct_args:
        if arg.is_array and arg.is_assumed_shape:
            if arg.array_rank == 1:
                lines.append(f"        CALL C_F_POINTER({arg.name}, {arg.name}_f, [n_{arg.name}])")
            elif arg.array_rank == 2:
                lines.append(f"        CALL C_F_POINTER({arg.name}, {arg.name}_f, "
                             f"[n_{arg.name}_rows, n_{arg.name}_cols])")
        else:
            lines.append(f"        CALL C_F_POINTER({arg.name}, {arg.name}_f)")

    # Flush C++ view modifications to Fortran type before calling the callee.
    # The C++ caller may have modified view scalars (e.g., setting default
    # parameter values) BEFORE this callee call. Without flushing, the post-call
    # re-sync would overwrite those modifications with stale values from the
    # original Fortran type.
    inout_view_args_for_flush = [
        (arg, mapping) for arg, mapping in view_struct_args
        if arg.intent and arg.intent.value.upper() in ("INOUT", "OUT")
    ]
    if inout_view_args_for_flush:
        lines.append(f"        ! Flush C++ modifications to Fortran before callee call")
        for arg, mapping in inout_view_args_for_flush:
            type_lower = mapping.c_type.lower()
            stash_name = f"vit_original_{type_lower}"
            reverse_copy = f"vit_copy_scalars_to_{type_lower}"
            lines.append(f"        CALL C_F_POINTER({arg.name}, {arg.name}_view)")
            lines.append(f"        CALL {reverse_copy}({arg.name}_view, {stash_name})")

    # Seed the CHARACTER locals from the C buffers. Done for EVERY intent,
    # including OUT: a Fortran callee is not required to assign every byte of
    # an INTENT(OUT) CHARACTER, and a direct Fortran call would have left the
    # caller's bytes in place.
    if char_stage_args:
        lines.append(f"        ! Stage CHARACTER args into Fortran-shaped locals")
    for arg, len_expr, count in char_stage_args:
        if count:
            lines.append(f"        DO vit_j_{arg.name} = 1, {count}")
            lines.append(f"            DO vit_i_{arg.name} = 1, {len_expr}")
            lines.append(f"                local_{arg.name}(vit_j_{arg.name})(vit_i_{arg.name}:vit_i_{arg.name}) = &")
            lines.append(f"                    {arg.name}((vit_j_{arg.name} - 1) * ({len_expr}) + vit_i_{arg.name})")
            lines.append(f"            END DO")
            lines.append(f"        END DO")
        else:
            lines.append(f"        DO vit_i_{arg.name} = 1, {len_expr}")
            lines.append(f"            local_{arg.name}(vit_i_{arg.name}:vit_i_{arg.name}) = {arg.name}(vit_i_{arg.name})")
            lines.append(f"        END DO")

    # Build the call to the original Fortran function.
    # OPTIONAL args require IF/ELSE branching — Fortran uses argument
    # presence (not a flag) to indicate optionality.
    optional_args = [a for a in sig.args if a.is_optional]
    required_call_args = _build_bridge_call_args(
        sig, kind_aliases, derived_types, skip_optional=True
    )
    required_str = ", ".join(required_call_args)

    def _make_call(func_name, args_str, is_function, result_name=None,
                   ret_mapping=None):
        """Generate a single CALL or assignment line."""
        if is_function and sig.result_is_array:
            # Array-returning function: assign result to output buffer
            size_expr = result_size_param or "SIZE(alpha)"
            return f"        {result_buffer_name}(1:{size_expr}) = {func_name}({args_str})"
        elif is_function and not sig.result_is_array:
            ret_type = sig.result_type or sig.args[0].fortran_type if sig.args else "REAL(8)"
            if ret_mapping and ret_mapping.c_kind != ret_mapping.fortran_kind and ret_mapping.fortran_kind:
                return f"        {result_name} = {ret_mapping.iso_c_type.split('(')[0]}({func_name}({args_str}), {ret_mapping.c_kind})"
            else:
                return f"        {result_name} = {func_name}({args_str})"
        else:
            return f"        CALL {func_name}({args_str})"

    if optional_args:
        # Generate IF/ELSE branching for OPTIONAL args.
        # For simplicity, handle up to 1 optional arg (covers all current cases).
        opt = optional_args[0]
        opt_mapping = get_type_mapping(opt.fortran_type, kind_aliases, derived_types)
        opt_call_name = opt.name
        if opt_mapping.iso_c_type.startswith("LOGICAL"):
            opt_call_name = f"LOGICAL({opt.name})"
        elif (opt_mapping.fortran_type.upper().lstrip().startswith("LOGICAL")
                and opt_mapping.iso_c_type.startswith("INTEGER")):
            opt_call_name = f"({opt.name} /= 0)"

        args_with = required_str + (", " if required_str else "") + opt_call_name
        args_without = required_str

        lines.append(f"        IF (has_{opt.name} /= 0) THEN")
        if sig.is_function and not result_is_out_param(sig, kind_aliases, derived_types):
            lines.append(_make_call(sig.name, args_with, True, result_name, ret_mapping))
        elif sig.is_function and sig.result_is_array:
            lines.append(_make_call(sig.name, args_with, True))
        else:
            lines.append(_make_call(sig.name, args_with, False))
        lines.append(f"        ELSE")
        if sig.is_function and not result_is_out_param(sig, kind_aliases, derived_types):
            lines.append(_make_call(sig.name, args_without, True, result_name, ret_mapping))
        elif sig.is_function and sig.result_is_array:
            lines.append(_make_call(sig.name, args_without, True))
        else:
            lines.append(_make_call(sig.name, args_without, False))
        lines.append(f"        END IF")
    else:
        if sig.is_function and not result_is_out_param(sig, kind_aliases, derived_types):
            lines.append(_make_call(sig.name, required_str, True, result_name, ret_mapping))
        elif sig.is_function and sig.result_is_array:
            lines.append(_make_call(sig.name, required_str, True))
        else:
            lines.append(_make_call(sig.name, required_str, False))

    # Re-sync view structs after the Fortran call, but only for INOUT/OUT args.
    # The Fortran function may have modified scalar fields in the original type
    # (via the stash). The C++ caller's view struct must reflect those changes
    # so the final reverse-copy doesn't overwrite them with stale values.
    # IN-only args are not modified — re-syncing them would corrupt the view
    # (the INTENT(OUT) populator zeros the struct before re-filling).
    inout_view_args = [
        (arg, mapping) for arg, mapping in view_struct_args
        if arg.intent and arg.intent.value.upper() in ("INOUT", "OUT")
    ]
    if inout_view_args:
        lines.append(f"        ! Re-sync view struct from Fortran type after callee modified it")
        for arg, mapping in inout_view_args:
            type_lower = mapping.c_type.lower()
            stash_name = f"vit_original_{type_lower}"
            populator = f"vit_populate_{type_lower}"
            lines.append(f"        CALL C_F_POINTER({arg.name}, {arg.name}_view)")
            lines.append(f"        CALL {populator}({stash_name}, {arg.name}_view)")

    # Copy the staged CHARACTER locals back to the C buffers. The full declared
    # width, not LEN_TRIM: Fortran CHARACTER is blank-padded and fixed width,
    # and stopping at the last non-blank would leave the caller's old bytes
    # visible past the end of a result that got shorter.
    writeback = [t for t in char_stage_args if _bridge_char_copies_back(t[0])]
    if writeback:
        lines.append(f"        ! Copy CHARACTER results back to the C buffers")
    for arg, len_expr, count in writeback:
        if count:
            lines.append(f"        DO vit_j_{arg.name} = 1, {count}")
            lines.append(f"            DO vit_i_{arg.name} = 1, {len_expr}")
            lines.append(f"                {arg.name}((vit_j_{arg.name} - 1) * ({len_expr}) + vit_i_{arg.name}) = &")
            lines.append(f"                    local_{arg.name}(vit_j_{arg.name})(vit_i_{arg.name}:vit_i_{arg.name})")
            lines.append(f"            END DO")
            lines.append(f"        END DO")
        else:
            lines.append(f"        DO vit_i_{arg.name} = 1, {len_expr}")
            lines.append(f"            {arg.name}(vit_i_{arg.name}) = local_{arg.name}(vit_i_{arg.name}:vit_i_{arg.name})")
            lines.append(f"        END DO")

    if sig.is_function and not result_is_out_param(sig, kind_aliases, derived_types):
        lines.append(f"    END FUNCTION {bridge_name}")
    else:
        lines.append(f"    END SUBROUTINE {bridge_name}")

    return "\n".join(lines)


def _build_bridge_call_args(sig: FortranSignature,
                             kind_aliases: Optional[dict] = None,
                             derived_types: Optional[dict] = None,
                             skip_optional: bool = False) -> list[str]:
    """
    Build argument list for the bridge's call to the original Fortran function.

    Converts C types back to Fortran types:
    - Struct pointers: use the C_F_POINTER'd local variable (arg_f)
    - LOGICAL: convert INTEGER(C_INT) back to LOGICAL via (/= 0)
    - Assumed-shape arrays with size params: skip the size param, pass array directly
    - Scalars: direct pass-through (implicit kind conversion)

    If skip_optional=True, OPTIONAL args are excluded entirely (caller handles
    them via IF/ELSE branching in the bridge).
    """
    call_args = []
    skip_next_size = False

    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)

        # Skip passthrough args
        if mapping.is_derived and not mapping.is_c_compatible:
            continue

        # OPTIONAL args: skip when building required-only list
        if arg.is_optional:
            if skip_optional:
                continue
            # Legacy path: pass through as-is (used when no branching)
            call_args.append(f"has_{arg.name}")
            if mapping.is_derived and mapping.is_c_compatible:
                call_args.append(f"{arg.name}_f")
            elif arg.is_array:
                call_args.append(arg.name)
            else:
                call_args.append(arg.name)
            continue

        # C-compatible derived type
        if mapping.is_derived and mapping.is_c_compatible:
            if arg.is_array and arg.is_assumed_shape:
                if arg.array_rank == 1:
                    call_args.append(f"{arg.name}_f(1:n_{arg.name})")
                elif arg.array_rank == 2:
                    call_args.append(
                        f"RESHAPE({arg.name}_f(1:n_{arg.name}_rows*n_{arg.name}_cols), "
                        f"(/ n_{arg.name}_rows, n_{arg.name}_cols /))")
            elif mapping.is_view_type:
                # View type → use module stash variable (not C_F_POINTER'd local,
                # because the view struct has a different memory layout)
                type_lower = mapping.c_type.lower()
                call_args.append(f"vit_original_{type_lower}")
            else:
                # Regular BIND(C) struct → use C_F_POINTER'd local
                call_args.append(f"{arg.name}_f")
            continue

        # CHARACTER of any shape: pass the staged local, never the raw C_CHAR
        # buffer. A scalar CHARACTER(*) dummy cannot receive a rank-1 array
        # ("Rank mismatch in argument"), and a CHARACTER array dummy would take
        # the flat buffer with the wrong element boundaries. Must be tested
        # before the is_array branch, which does not know about element length.
        if mapping.iso_c_type.startswith("CHARACTER"):
            call_args.append(f"local_{arg.name}")
            continue

        if arg.is_array:
            if arg.is_assumed_shape:
                # The bridge receives assumed-size (*) arrays from C, but the
                # Fortran callee expects assumed-shape (:) or (:,:). Passing
                # (*) to (:) is illegal. Use explicit sections which create
                # temporaries compatible with assumed-shape.
                if arg.array_rank == 1:
                    call_args.append(f"{arg.name}(1:n_{arg.name})")
                elif arg.array_rank == 2:
                    call_args.append(
                        f"RESHAPE({arg.name}(1:n_{arg.name}_rows*n_{arg.name}_cols), "
                        f"(/ n_{arg.name}_rows, n_{arg.name}_cols /))"
                    )
                # Skip the synthetic size param(s) (Fortran original doesn't expect them)
            else:
                # Fixed-size arrays: pass directly (no size mismatch)
                call_args.append(arg.name)
            continue

        # Scalar args — INOUT args must be passed directly (no conversion wrapping).
        # VALUE args may need kind conversion for LOGICAL.
        if arg.intent in (IntentKind.OUT, IntentKind.INOUT):
            # INOUT/OUT: pass directly — can't wrap in conversion function.
            # (CHARACTER is handled above, for every intent.)
            call_args.append(arg.name)
        elif mapping.iso_c_type.startswith("LOGICAL("):
            # LOGICAL(C_BOOL) → LOGICAL: explicit conversion needed
            call_args.append(f"LOGICAL({arg.name})")
        elif (mapping.fortran_type.upper().lstrip().startswith("LOGICAL")
                and mapping.iso_c_type.startswith("INTEGER")):
            # type_map sends Fortran LOGICAL across as INTEGER(C_INT), which is
            # the right memory layout but is NOT assignment-compatible: passing
            # the INTEGER straight to a LOGICAL dummy is a hard compile error.
            # The wrapper direction already converts (MERGE going out); this is
            # the same conversion coming back IN, which the bridge never did.
            call_args.append(f"({arg.name} /= 0)")
        else:
            # Scalar VALUE args: direct pass-through.
            # BIND(C) VALUE args are already the right type for calling Fortran
            # (gfortran handles implicit kind promotion for REAL/INTEGER).
            call_args.append(arg.name)

    return call_args


def generate_callee_declarations_header(
    callee_sigs: list,
    kind_aliases: Optional[dict] = None,
    derived_types: Optional[dict] = None,
) -> str:
    """
    Generate a C header with extern "C" declarations for kernel callee bridges.

    This header is included by the kernel C++ wrapper so the translation
    can call callee_c() functions.
    """
    lines = []
    lines.append("// VIT: Kernel callee bridge declarations")
    lines.append("// Auto-generated — allows C++ translations to call")
    lines.append("// original Fortran functions via BIND(C) bridges.")
    lines.append("")
    lines.append("#ifndef VIT_KERNEL_CALLEES_H")
    lines.append("#define VIT_KERNEL_CALLEES_H")
    lines.append("")
    lines.append('#ifdef __cplusplus')
    lines.append('extern "C" {')
    lines.append('#endif')
    lines.append("")

    for sig in callee_sigs:
        params = build_c_params(sig, kind_aliases, derived_types)
        param_str = ", ".join(f"{p[0]} {p[1]}" for p in params)
        if sig.is_function and not result_is_out_param(sig, kind_aliases, derived_types):
            ret_mapping = _get_return_type_mapping(sig, kind_aliases, derived_types)
            lines.append(f"{ret_mapping.c_type} {sig.c_func_name}({param_str});")
        else:
            # Subroutine or array-returning function (result buffer already in params)
            lines.append(f"void {sig.c_func_name}({param_str});")

    lines.append("")
    lines.append('#ifdef __cplusplus')
    lines.append('}')
    lines.append('#endif')
    lines.append("")
    lines.append("#endif // VIT_KERNEL_CALLEES_H")
    lines.append("")

    return "\n".join(lines)
