"""
Deterministic Fortran ↔ C++ interface generation.

Given a parsed Fortran function signature, generates:
1. C++ extern "C" wrapper that calls the user-provided C++ implementation
2. Fortran INTERFACE block with ISO_C_BINDING
3. Fortran wrapper function that replaces the original

This is NOT an LLM task — the mapping is fully mechanical.
"""

from pathlib import Path
from typing import Optional

from .fortran_parser import FortranSignature, SubprogramKind, IntentKind, FortranArg
from .type_map import get_type_mapping, TypeMapping


def generate_cpp_wrapper(sig: FortranSignature, cpp_impl_file: str,
                         kind_aliases: Optional[dict] = None) -> str:
    """
    Generate the C++ source file with extern "C" wrapper.

    The file includes the user's C++ implementation and wraps it with
    an extern "C" function that Fortran can call via ISO_C_BINDING.

    Args:
        sig: Parsed Fortran function signature
        cpp_impl_file: Path to user's C++ implementation file
        kind_aliases: Project-specific kind aliases

    Returns:
        Complete C++ source code string
    """
    lines = []
    lines.append(f"// Auto-generated C wrapper for Fortran function: {sig.name}")
    lines.append(f"// Generated by VIT (Verified Incremental Translator)")
    lines.append("")

    # Include standard headers based on types used
    headers = set()
    headers.add("<algorithm>")  # For std::min, std::max (common in scientific code)
    headers.add("<cmath>")      # For math functions
    lines.extend(f"#include {h}" for h in sorted(headers))
    lines.append("")

    # Forward-declare or include the user's implementation
    # The user's C++ function should have the same signature as the Fortran original
    # but with C types
    impl_name = sig.name.lower()
    c_func_name = sig.c_func_name

    # Include the user's implementation inline
    lines.append(f"// User-provided C++ implementation")
    lines.append(f'#include "{Path(cpp_impl_file).name}"')
    lines.append("")

    # Generate extern "C" wrapper
    if sig.is_function:
        ret_mapping = _get_return_type_mapping(sig, kind_aliases)
        ret_c_type = ret_mapping.c_type

        # Build parameter list
        params = _build_c_params(sig, kind_aliases)
        param_str = ", ".join(f"{p[0]} {p[1]}" for p in params)

        lines.append(f'extern "C" {{')
        lines.append(f"    {ret_c_type} {c_func_name}({param_str}) {{")

        # Call the user's implementation
        arg_str = ", ".join(p[1] for p in params)
        lines.append(f"        return {impl_name}({arg_str});")

        lines.append(f"    }}")
        lines.append(f"}}")

    else:  # Subroutine
        params = _build_c_params(sig, kind_aliases)
        param_str = ", ".join(f"{p[0]} {p[1]}" for p in params)

        lines.append(f'extern "C" {{')
        lines.append(f"    void {c_func_name}({param_str}) {{")

        arg_str = ", ".join(p[1] for p in params)
        lines.append(f"        {impl_name}({arg_str});")

        lines.append(f"    }}")
        lines.append(f"}}")

    lines.append("")
    return "\n".join(lines)


def generate_fortran_interface_block(sig: FortranSignature,
                                     kind_aliases: Optional[dict] = None) -> str:
    """
    Generate the Fortran INTERFACE block for the C function.

    This goes inside the module that contains the original function,
    ABOVE the CONTAINS statement.
    """
    lines = []
    c_func_name = sig.c_func_name

    lines.append(f"    ! Auto-generated interface for C++ implementation of {sig.name}")
    lines.append(f"    INTERFACE")

    if sig.is_function:
        ret_mapping = _get_return_type_mapping(sig, kind_aliases)

        # Build arg list
        arg_names = [a.name for a in sig.args]
        arg_str = ", ".join(arg_names)

        lines.append(f"        FUNCTION {c_func_name}({arg_str}) BIND(C, NAME='{c_func_name}')")
        lines.append(f"            USE ISO_C_BINDING")

        # Declare each argument
        for arg in sig.args:
            mapping = get_type_mapping(arg.fortran_type, kind_aliases)
            if arg.is_array:
                # Arrays are passed by reference in C interop
                lines.append(f"            {mapping.iso_c_type}, INTENT({arg.intent.value or 'IN'}) :: {arg.name}{_format_dims(arg)}")
            else:
                # Scalars passed by VALUE
                lines.append(f"            {mapping.iso_c_type}, VALUE :: {arg.name}")

        # Declare return type
        lines.append(f"            {ret_mapping.iso_c_type} :: {c_func_name}")
        lines.append(f"        END FUNCTION {c_func_name}")

    else:  # Subroutine
        arg_names = [a.name for a in sig.args]
        arg_str = ", ".join(arg_names)

        lines.append(f"        SUBROUTINE {c_func_name}({arg_str}) BIND(C, NAME='{c_func_name}')")
        lines.append(f"            USE ISO_C_BINDING")

        for arg in sig.args:
            mapping = get_type_mapping(arg.fortran_type, kind_aliases)
            if arg.is_array:
                intent_str = arg.intent.value or "INOUT"
                lines.append(f"            {mapping.iso_c_type}, INTENT({intent_str}) :: {arg.name}{_format_dims(arg)}")
            else:
                if arg.intent in (IntentKind.OUT, IntentKind.INOUT):
                    # OUT/INOUT args can't be VALUE
                    intent_str = arg.intent.value
                    lines.append(f"            {mapping.iso_c_type}, INTENT({intent_str}) :: {arg.name}")
                else:
                    lines.append(f"            {mapping.iso_c_type}, VALUE :: {arg.name}")

        lines.append(f"        END SUBROUTINE {c_func_name}")

    lines.append(f"    END INTERFACE")

    return "\n".join(lines)


def generate_fortran_wrapper(sig: FortranSignature,
                             kind_aliases: Optional[dict] = None) -> str:
    """
    Generate the Fortran wrapper function that replaces the original.

    The wrapper:
    1. Has the same signature as the original function
    2. Converts arguments from project kinds to C kinds
    3. Calls the C function via the interface
    4. Converts the result back to the project kind
    """
    lines = []
    c_func_name = sig.c_func_name

    if sig.is_function:
        # Function header
        arg_str = ", ".join(a.name for a in sig.args)
        result_name = sig.result_name or f"{sig.name}_result"
        lines.append(f"    FUNCTION {sig.name}({arg_str}) RESULT({result_name})")
        lines.append(f"        USE ISO_C_BINDING")
        lines.append(f"        IMPLICIT NONE")

        # Declare arguments with original types
        for arg in sig.args:
            intent_str = f", INTENT({arg.intent.value})" if arg.intent != IntentKind.NONE else ", INTENT(IN)"
            if arg.is_array:
                lines.append(f"        {arg.fortran_type}{intent_str} :: {arg.name}{_format_dims(arg)}")
            else:
                lines.append(f"        {arg.fortran_type}{intent_str} :: {arg.name}")

        # Declare result with original type
        ret_type = sig.result_type or sig.args[0].fortran_type if sig.args else "REAL(8)"
        lines.append(f"        {ret_type} :: {result_name}")

        # Build the C function call with type conversions
        ret_mapping = _get_return_type_mapping(sig, kind_aliases)
        converted_args = []
        for arg in sig.args:
            mapping = get_type_mapping(arg.fortran_type, kind_aliases)
            if arg.is_array:
                # Arrays don't need conversion — they're passed by reference
                converted_args.append(arg.name)
            elif mapping.c_kind != mapping.fortran_kind and mapping.fortran_kind:
                # Need to convert from project kind to C kind
                converted_args.append(f"REAL({arg.name}, {mapping.c_kind})")
            else:
                converted_args.append(arg.name)

        call_str = ", ".join(converted_args)

        # Convert result back to project kind if needed
        c_call = f"{c_func_name}({call_str})"

        # Get the original kind name for the result (preserve case from source)
        ret_type_stripped = ret_type.strip()
        ret_type_upper = ret_type_stripped.upper()
        if "(" in ret_type_stripped:
            ret_kind = ret_type_stripped[ret_type_stripped.index("(") + 1:ret_type_stripped.rindex(")")]
        else:
            ret_kind = None

        if ret_kind and ret_kind.upper() != ret_mapping.c_kind.upper():
            lines.append(f"        {result_name} = REAL({c_call}, {ret_kind})")
        else:
            lines.append(f"        {result_name} = {c_call}")

        lines.append(f"    END FUNCTION {sig.name}")

    else:  # Subroutine
        arg_str = ", ".join(a.name for a in sig.args)
        lines.append(f"    SUBROUTINE {sig.name}({arg_str})")
        lines.append(f"        USE ISO_C_BINDING")
        lines.append(f"        IMPLICIT NONE")

        for arg in sig.args:
            intent_str = f", INTENT({arg.intent.value})" if arg.intent != IntentKind.NONE else ""
            if arg.is_array:
                lines.append(f"        {arg.fortran_type}{intent_str} :: {arg.name}{_format_dims(arg)}")
            else:
                lines.append(f"        {arg.fortran_type}{intent_str} :: {arg.name}")

        # Build call with conversions
        converted_args = []
        for arg in sig.args:
            mapping = get_type_mapping(arg.fortran_type, kind_aliases)
            if arg.is_array:
                converted_args.append(arg.name)
            elif arg.intent in (IntentKind.OUT, IntentKind.INOUT):
                converted_args.append(arg.name)
            elif mapping.c_kind != mapping.fortran_kind and mapping.fortran_kind:
                base = mapping.iso_c_type.split("(")[0]
                converted_args.append(f"{base}({arg.name}, {mapping.c_kind})")
            else:
                converted_args.append(arg.name)

        call_str = ", ".join(converted_args)
        lines.append(f"        CALL {c_func_name}({call_str})")
        lines.append(f"    END SUBROUTINE {sig.name}")

    return "\n".join(lines)


def generate_kernel_makefile_patch(sig: FortranSignature,
                                   cpp_source_name: str) -> str:
    """
    Generate the Makefile additions needed for KGen kernel verification.

    Encodes the lessons learned from our ROSCO experience:
    - FC_0 and FC_FLAGS_SET_0 variables
    - C++ compilation rule
    - -lstdc++ link flag
    """
    obj_name = cpp_source_name.replace(".cpp", ".o")

    return f"""
# === VIT: C++ integration for {sig.name} ===
# Add these to the kernel Makefile

# Ensure FC_0 is defined (KGen sometimes uses FC_0 instead of FC)
FC_0 ?= $(FC)
FC_FLAGS_SET_0 ?= $(FC_FLAGS)

# C++ compilation rule
CXX ?= g++
CXXFLAGS ?= -O2 -fPIC

{obj_name}: {cpp_source_name}
\t$(CXX) $(CXXFLAGS) -c $< -o $@

# Add {obj_name} to ALL_OBJS
# Add -lstdc++ to link flags
# === End VIT additions ===
"""


def generate_cmake_patch(sig: FortranSignature,
                         cpp_source_name: str,
                         target_name: str = "discon") -> str:
    """
    Generate CMakeLists.txt additions for codebase integration.
    """
    return f"""
# === VIT: C++ integration for {sig.name} ===
enable_language(CXX)
# Add {cpp_source_name} to the source list for target {target_name}
# target_link_libraries({target_name} PRIVATE stdc++)
# === End VIT additions ===
"""


# --- Internal helpers ---

def _get_return_type_mapping(sig: FortranSignature,
                             kind_aliases: Optional[dict] = None) -> TypeMapping:
    """Get the type mapping for a function's return type."""
    if sig.result_type:
        return get_type_mapping(sig.result_type, kind_aliases)
    # Fallback: try to infer from result variable name or first arg
    # This is a heuristic — explicit RESULT type is preferred
    return get_type_mapping("REAL(8)", kind_aliases)


def _build_c_params(sig: FortranSignature,
                    kind_aliases: Optional[dict] = None) -> list[tuple[str, str]]:
    """Build the C parameter list: [(c_type, param_name), ...]"""
    params = []
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases)
        if arg.is_array:
            params.append((f"{mapping.c_type}*", arg.name))
        else:
            params.append((mapping.c_type, arg.name))
    return params


def _format_dims(arg: FortranArg) -> str:
    """Format array dimension spec for Fortran declarations."""
    if arg.array_dims:
        return f"({arg.array_dims})"
    return ""