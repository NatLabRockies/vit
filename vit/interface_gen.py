"""
Deterministic Fortran ↔ C++ interface generation.

Given a parsed Fortran function signature, generates:
1. C++ extern "C" wrapper that calls the user-provided C++ implementation
2. Fortran INTERFACE block with ISO_C_BINDING
3. Fortran wrapper function that replaces the original

This is NOT an LLM task — the mapping is fully mechanical.

Handles derived types, assumed-shape arrays, and OPTIONAL arguments:
- Derived types that are C-compatible are passed as struct pointers
  (TYPE(C_PTR) VALUE in Fortran, struct_t* in C).
- Derived types that are NOT C-compatible are "passthrough" args:
  accepted by the Fortran wrapper but NOT forwarded to the C function.
- Assumed-shape arrays (DIMENSION(:)) become assumed-size (*) in the
  BIND(C) interface, with a synthetic size parameter inserted.
- OPTIONAL arguments are split into a flag (has_name) + value pair.
- Scalar INTENT(OUT/INOUT) args are always pointers, regardless of
  whether the subprogram is a function or subroutine.
"""

import re
from pathlib import Path
from typing import Optional

from .fortran_parser import FortranSignature, IntentKind, FortranArg
from .type_map import get_type_mapping, TypeMapping, normalize_fortran_type


def _fortran_kind_byte_size(kind: str) -> int:
    """Return the byte size for a Fortran kind parameter (numeric or named)."""
    try:
        k = int(kind)
        return k  # Numeric kinds like "8" = 8 bytes, "4" = 4 bytes
    except ValueError:
        return 0  # Unknown named kind — can't determine size


def _resolve_fortran_type(fortran_type: str, kind_aliases: Optional[dict] = None) -> str:
    """Resolve project-specific kind aliases in a Fortran type string.

    Converts e.g. REAL(ReKi) → REAL(8) using kind_aliases, so the wrapper
    function is self-contained and doesn't need USE statements for kind modules.
    Derived types (TYPE(...)) pass through unchanged.
    """
    if not kind_aliases:
        return fortran_type
    resolved = normalize_fortran_type(fortran_type, kind_aliases)
    # normalize_fortran_type uppercases — preserve original casing style
    # by using the resolved form only (it's standard Fortran, casing doesn't matter)
    return resolved


def _is_passthrough(arg: FortranArg, kind_aliases: Optional[dict] = None,
                    derived_types: Optional[dict] = None) -> bool:
    """Check if an argument is a passthrough (non-C-compatible derived type)."""
    mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
    return mapping.is_derived and not mapping.is_c_compatible


def generate_cpp_wrapper(sig: FortranSignature, cpp_impl_file: str,
                         kind_aliases: Optional[dict] = None,
                         derived_types: Optional[dict] = None,
                         struct_headers: Optional[list[str]] = None) -> str:
    """
    Generate the C++ source file with extern "C" wrapper.

    The file includes the user's C++ implementation and wraps it with
    an extern "C" function that Fortran can call via ISO_C_BINDING.

    Args:
        sig: Parsed Fortran function signature
        cpp_impl_file: Path to user's C++ implementation file
        kind_aliases: Project-specific kind aliases
        derived_types: Registry of known derived types
        struct_headers: List of struct header filenames to #include

    Returns:
        Complete C++ source code string
    """
    lines = []
    lines.append(f"// Auto-generated C wrapper for Fortran function: {sig.name}")
    lines.append(f"// Generated by VIT (Verified Incremental Translator)")
    lines.append("")

    # Include struct headers for C-compatible derived types
    if struct_headers:
        for h in struct_headers:
            lines.append(f'#include "{h}"')
        lines.append("")

    impl_name = sig.cpp_impl_name
    c_func_name = sig.c_func_name

    # Include the user's implementation inline
    lines.append(f"// User-provided C++ implementation")
    lines.append(f'#include "{Path(cpp_impl_file).name}"')
    lines.append("")

    lines.extend(generate_vit_free_definition(sig))

    # Generate extern "C" wrapper
    if sig.is_function and not result_is_out_param(sig, kind_aliases, derived_types):
        # Scalar-returning function: return value directly
        ret_mapping = _get_return_type_mapping(sig, kind_aliases, derived_types)
        ret_c_type = ret_mapping.c_type

        # Build parameter list (skips passthrough, adds size params for arrays)
        params = build_c_params(sig, kind_aliases, derived_types)
        param_str = ", ".join(f"{p[0]} {p[1]}" for p in params)

        lines.append(f'extern "C" {{')
        lines.append(f"    {ret_c_type} {c_func_name}({param_str}) {{")

        # Call the user's implementation
        arg_str = ", ".join(p[1] for p in params)
        lines.append(f"        return {impl_name}({arg_str});")

        lines.append(f"    }}")
        lines.append(f"}}")

    else:  # Subroutine or array-valued function (both use void + output params)
        params = build_c_params(sig, kind_aliases, derived_types)
        param_str = ", ".join(f"{p[0]} {p[1]}" for p in params)

        lines.append(f'extern "C" {{')
        lines.append(f"    void {c_func_name}({param_str}) {{")

        arg_str = ", ".join(p[1] for p in params)
        lines.append(f"        {impl_name}({arg_str});")

        lines.append(f"    }}")
        lines.append(f"}}")

    lines.append("")
    return "\n".join(lines)


def generate_fortran_interface_block(sig: FortranSignature,
                                     kind_aliases: Optional[dict] = None,
                                     derived_types: Optional[dict] = None) -> str:
    """
    Generate the Fortran INTERFACE block for the C function.

    This goes inside the module that contains the original function,
    ABOVE the CONTAINS statement.

    Passthrough args (non-C-compatible derived types) are excluded.
    Assumed-shape arrays become assumed-size (*) with size parameters.
    """
    lines = []
    c_func_name = sig.c_func_name

    # Build the list of C-interface args (excluding passthrough)
    c_args = _build_interface_args(sig, kind_aliases, derived_types)

    lines.append(f"    ! Auto-generated interface for C++ implementation of {sig.name}")
    lines.append(f"    INTERFACE")

    if sig.is_function and not result_is_out_param(sig, kind_aliases, derived_types):
        # Scalar-returning function: BIND(C) FUNCTION with return type
        ret_mapping = _get_return_type_mapping(sig, kind_aliases, derived_types)

        # Build arg name list for interface declaration
        arg_names = [a["iface_name"] for a in c_args]
        arg_str = ", ".join(arg_names)

        lines.append(f"        FUNCTION {c_func_name}({arg_str}) BIND(C, NAME='{c_func_name}')")
        lines.append(f"            USE ISO_C_BINDING")

        # Declare each argument
        for a in c_args:
            lines.append(f"            {a['iface_decl']}")

        # Declare return type
        lines.append(f"            {ret_mapping.iso_c_type} :: {c_func_name}")
        lines.append(f"        END FUNCTION {c_func_name}")

    else:  # Subroutine or array-valued function (both use BIND(C) SUBROUTINE)
        arg_names = [a["iface_name"] for a in c_args]
        arg_str = ", ".join(arg_names)

        lines.append(f"        SUBROUTINE {c_func_name}({arg_str}) BIND(C, NAME='{c_func_name}')")
        lines.append(f"            USE ISO_C_BINDING")

        for a in c_args:
            lines.append(f"            {a['iface_decl']}")

        lines.append(f"        END SUBROUTINE {c_func_name}")

    lines.append(f"    END INTERFACE")

    return "\n".join(lines)


def generate_fortran_wrapper(sig: FortranSignature,
                             kind_aliases: Optional[dict] = None,
                             derived_types: Optional[dict] = None,
                             is_kernel: bool = False,
                             reverse_copy: bool = False,
                             allocations: Optional[list] = None) -> str:
    """
    Generate the Fortran wrapper function that replaces the original.

    The wrapper:
    1. Has the same signature as the original function (ALL args, including passthrough)
    2. Adds USE statements for modules providing derived types
    3. Converts arguments from project kinds to C kinds
    4. Calls the C function via the interface (excluding passthrough args)
    5. Converts the result back to the project kind
    6. For OPTIONAL args: declares local flag+value variables with PRESENT() checks
    7. For C-compatible derived types: adds TARGET attribute, uses C_LOC()

    Args:
        is_kernel: If True, generates kernel-specific code (view-type stash for
                   callee bridges). If False (default), generates integration code.
    """
    lines = []
    c_func_name = sig.c_func_name

    # Identify OPTIONAL args that are forwarded to C (not passthrough)
    optional_forwarded = [
        a for a in sig.args
        if a.is_optional and not _is_passthrough(a, kind_aliases, derived_types)
    ]

    view_args = _get_view_type_args(sig, kind_aliases, derived_types)

    if sig.is_function:
        lines.extend(_generate_wrapper_function(
            sig, c_func_name, kind_aliases, derived_types, optional_forwarded,
            view_args, is_kernel, reverse_copy
        ))
    else:
        lines.extend(_generate_wrapper_subroutine(
            sig, c_func_name, kind_aliases, derived_types, optional_forwarded,
            view_args, is_kernel, reverse_copy, allocations
        ))

    return "\n".join(lines)


def _generate_wrapper_function(sig, c_func_name, kind_aliases, derived_types,
                                optional_forwarded, view_args=None,
                                is_kernel=False, reverse_copy=False):
    """Generate wrapper body for a FUNCTION."""
    view_args = view_args or []
    lines = []

    # Function header — includes ALL args
    arg_str = ", ".join(a.name for a in sig.args)
    result_name = sig.result_name or f"{sig.name}_result"
    lines.append(f"    FUNCTION {sig.name}({arg_str}) RESULT({result_name})")
    lines.append(f"        USE ISO_C_BINDING")

    # Add USE statements for modules providing derived types
    for use_stmt in _get_use_statements_for_derived_types(sig):
        lines.append(f"        {use_stmt}")

    # Add USE for view type modules (include reverse-copy if requested)
    lines.extend(_get_view_use_statements(view_args, is_kernel, reverse_copy))

    lines.append(f"        IMPLICIT NONE")

    # Declare arguments — non-CHARACTER first so INTEGER length params are
    # declared before CHARACTER(len_param) args that depend on them.
    # Resolve kind aliases (e.g., REAL(ReKi) → REAL(8)) so the wrapper is
    # self-contained and doesn't need USE statements for project kind modules.
    char_args = []
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        if mapping.character_len_param or (mapping.character_length and mapping.character_length > 1):
            char_args.append(arg)
            continue
        resolved_type = _resolve_fortran_type(arg.fortran_type, kind_aliases)
        intent_str = f", INTENT({arg.intent.value})" if arg.intent != IntentKind.NONE else ", INTENT(IN)"
        optional_str = ", OPTIONAL" if arg.is_optional else ""
        target_str = _get_target_attr(arg, kind_aliases, derived_types)
        # An allocate-on-return dummy MUST keep its ALLOCATABLE attribute:
        # dropping it leaves a wrapper whose interface no longer matches the
        # actual argument at the call site.
        alloc_str = ", ALLOCATABLE" if is_alloc_return(arg) else ""
        if arg.is_array:
            lines.append(f"        {resolved_type}{intent_str}{optional_str}{alloc_str}{target_str} :: {arg.name}{_format_dims(arg)}")
        else:
            lines.append(f"        {resolved_type}{intent_str}{optional_str}{target_str} :: {arg.name}")
    for arg in char_args:
        resolved_type = _resolve_fortran_type(arg.fortran_type, kind_aliases)
        intent_str = f", INTENT({arg.intent.value})" if arg.intent != IntentKind.NONE else ", INTENT(IN)"
        lines.append(f"        {resolved_type}{intent_str} :: {arg.name}{_format_dims(arg)}")

    # Declare result with resolved type
    if sig.result_type:
        ret_type = _resolve_fortran_type(sig.result_type, kind_aliases)
    elif sig.args:
        ret_type = _resolve_fortran_type(sig.args[0].fortran_type, kind_aliases)
    else:
        raise ValueError(
            f"Cannot determine result type for wrapper of '{sig.name}'. "
            f"Function has no result_type and no arguments to infer from."
        )
    if sig.result_is_array and sig.result_dims:
        lines.append(f"        {ret_type}, DIMENSION({sig.result_dims}) :: {result_name}")
    else:
        lines.append(f"        {ret_type} :: {result_name}")

    # CHARACTER local var declarations (before any executable statements)
    lines.extend(_generate_character_declarations(sig, kind_aliases, derived_types))

    # Allocate-on-return locals + the vit_free interface
    lines.extend(_generate_alloc_return_declarations(sig, kind_aliases))

    # C_PTR locals for arguments that may alias a component of a view arg
    lines.extend(_alias_cptr_declarations(sig, kind_aliases, derived_types))

    # Staging INTEGER(C_INT) locals for by-reference LOGICAL arguments
    lines.extend(_logical_ref_declarations(sig, kind_aliases, derived_types))

    # CHARACTER-valued result: stage it in a C_CHAR buffer. A CHARACTER(n)
    # scalar cannot be passed to a BIND(C) CHARACTER(KIND=C_CHAR) array dummy,
    # so the C side fills the buffer and the wrapper copies it into the result.
    res_char_len = result_char_len(sig, kind_aliases, derived_types)
    if res_char_len:
        lines.append(f"        CHARACTER(KIND=C_CHAR) :: {result_name}_c({res_char_len})")
        lines.append(f"        INTEGER :: vit_i_result")

    # OPTIONAL preamble: local variables, PRESENT() checks
    if optional_forwarded:
        lines.extend(_generate_optional_preamble(optional_forwarded, kind_aliases, derived_types))

    # View type preamble: local view structs + populator calls
    if view_args:
        lines.extend(_generate_view_preamble(view_args, is_kernel))

    # CHARACTER copy loops (executable, before the C call)
    lines.extend(_generate_character_copy_loops(sig, kind_aliases, derived_types))

    # Allocate-on-return handshake variables
    lines.extend(_generate_alias_resolution(sig, kind_aliases, derived_types))
    lines.extend(_generate_logical_ref_prologue(sig, kind_aliases, derived_types))
    lines.extend(_generate_alloc_return_prologue(sig))

    # Build the C function call (only non-passthrough args, with size params for arrays)
    ret_mapping = _get_return_type_mapping(sig, kind_aliases, derived_types)
    call_args = _build_wrapper_call_args(sig, kind_aliases, derived_types)
    call_str = ", ".join(call_args)

    if result_is_out_param(sig, kind_aliases, derived_types):
        # Array- or CHARACTER-valued result: CALL the C subroutine, which
        # writes into result_name (or, for CHARACTER, into its C_CHAR buffer).
        lines.append(f"        CALL {c_func_name}({call_str})")
    else:
        # Scalar result: assign from C function return value
        c_call = f"{c_func_name}({call_str})"

        # Get the original kind name for the result (preserve case from source)
        ret_type_stripped = ret_type.strip()
        if "(" in ret_type_stripped:
            ret_kind = ret_type_stripped[ret_type_stripped.index("(") + 1:ret_type_stripped.rindex(")")]
        else:
            ret_kind = None

        if ret_kind and ret_kind.upper() != ret_mapping.c_kind.upper():
            lines.append(f"        {result_name} = REAL({c_call}, {ret_kind})")
        else:
            lines.append(f"        {result_name} = {c_call}")

    # Allocate-on-return: allocate the dummy, copy, free
    lines.extend(_generate_alloc_return_epilogue(sig))
    lines.extend(_generate_logical_ref_epilogue(sig, kind_aliases, derived_types))

    # Reverse-copy: copy modified scalars from view back to Fortran type.
    # Placed after the result assignment, since the C call is what mutates the
    # view. Mirrors the block in _generate_wrapper_subroutine.
    if reverse_copy and view_args:
        lines.append(f"        ! Copy modified scalars back from view to Fortran type")
        for arg, mapping in view_args:
            if arg.intent and arg.intent.value.upper() in ("INOUT", "OUT"):
                type_lower = mapping.c_type.lower()
                if arg.is_array and not arg.is_assumed_shape and arg.array_dims:
                    lines.append(f"        DO vit_view_i = 1, {arg.array_dims}")
                    lines.append(f"            CALL vit_copy_scalars_to_{type_lower}({arg.name}_view(vit_view_i), {arg.name}(vit_view_i))")
                    lines.append(f"        END DO")
                else:
                    lines.append(f"        CALL vit_copy_scalars_to_{type_lower}({arg.name}_view, {arg.name})")

    # Copy the C_CHAR result buffer back into the CHARACTER result. The C side
    # is required to have filled all res_char_len bytes -- Fortran CHARACTER is
    # blank-padded and fixed width, not NUL-terminated.
    if res_char_len:
        lines.append(f"        DO vit_i_result = 1, {res_char_len}")
        lines.append(f"            {result_name}(vit_i_result:vit_i_result) = {result_name}_c(vit_i_result)")
        lines.append(f"        END DO")

    lines.append(f"    END FUNCTION {sig.name}")
    return lines


def _generate_wrapper_subroutine(sig, c_func_name, kind_aliases, derived_types,
                                  optional_forwarded, view_args=None,
                                  is_kernel=False, reverse_copy=False,
                                  allocations=None):
    """Generate wrapper body for a SUBROUTINE."""
    view_args = view_args or []
    lines = []

    arg_str = ", ".join(a.name for a in sig.args)
    lines.append(f"    SUBROUTINE {sig.name}({arg_str})")
    lines.append(f"        USE ISO_C_BINDING")

    # Add USE statements for modules providing derived types
    for use_stmt in _get_use_statements_for_derived_types(sig):
        lines.append(f"        {use_stmt}")

    # Add USE for view type modules (include reverse-copy if requested)
    lines.extend(_get_view_use_statements(view_args, is_kernel, reverse_copy))

    lines.append(f"        IMPLICIT NONE")

    # Declare arguments — non-CHARACTER first so INTEGER length params are
    # declared before CHARACTER(len_param) args that depend on them.
    # Resolve kind aliases (e.g., REAL(ReKi) → REAL(8)) so the wrapper is
    # self-contained and doesn't need USE statements for project kind modules.
    char_args = []
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        if mapping.character_len_param or (mapping.character_length and mapping.character_length > 1):
            char_args.append(arg)
            continue
        resolved_type = _resolve_fortran_type(arg.fortran_type, kind_aliases)
        intent_str = f", INTENT({arg.intent.value})" if arg.intent != IntentKind.NONE else ""
        optional_str = ", OPTIONAL" if arg.is_optional else ""
        target_str = _get_target_attr(arg, kind_aliases, derived_types)
        # An allocate-on-return dummy MUST keep its ALLOCATABLE attribute:
        # dropping it leaves a wrapper whose interface no longer matches the
        # actual argument at the call site.
        alloc_str = ", ALLOCATABLE" if is_alloc_return(arg) else ""
        if arg.is_array:
            lines.append(f"        {resolved_type}{intent_str}{optional_str}{alloc_str}{target_str} :: {arg.name}{_format_dims(arg)}")
        else:
            lines.append(f"        {resolved_type}{intent_str}{optional_str}{target_str} :: {arg.name}")
    for arg in char_args:
        resolved_type = _resolve_fortran_type(arg.fortran_type, kind_aliases)
        intent_str = f", INTENT({arg.intent.value})" if arg.intent != IntentKind.NONE else ""
        lines.append(f"        {resolved_type}{intent_str} :: {arg.name}{_format_dims(arg)}")

    # CHARACTER local var declarations (before any executable statements)
    lines.extend(_generate_character_declarations(sig, kind_aliases, derived_types))

    # Allocate-on-return locals + the vit_free interface
    lines.extend(_generate_alloc_return_declarations(sig, kind_aliases))

    # C_PTR locals for arguments that may alias a component of a view arg
    lines.extend(_alias_cptr_declarations(sig, kind_aliases, derived_types))

    # Staging INTEGER(C_INT) locals for by-reference LOGICAL arguments
    lines.extend(_logical_ref_declarations(sig, kind_aliases, derived_types))

    # View type declarations (must be before any executable statements)
    if view_args:
        lines.extend(_generate_view_declarations(view_args))

    # OPTIONAL preamble (declarations + executable IF-PRESENT checks)
    if optional_forwarded:
        lines.extend(_generate_optional_preamble(optional_forwarded, kind_aliases, derived_types))

    # Allocation-related local declarations
    if allocations:
        lines.append(f"        INTEGER(4) :: ErrStat2")
        lines.append(f"        CHARACTER(ErrMsgLen) :: ErrMsg2")
        lines.append(f"        CHARACTER(*), PARAMETER :: RoutineName = '{sig.name}'")
        has_copy = any(a.copy_call for a in allocations)
        if has_copy:
            lines.append(f"        INTEGER :: vit_alloc_i")

    # Auto-extracted ALLOCATE statements (before view populate, so C_LOC has valid memory)
    if allocations:
        all_allocs = [a for a in allocations if a.category in ("safe", "same_arg")]
        unsafe_allocs = [a for a in allocations if a.category == "local"]
        if all_allocs:
            lines.append(f"        ! --- Pre-allocate arrays (auto-extracted from Fortran source) ---")
            current_guard: Optional[str] = None
            for a in all_allocs:
                desired_guard = a.guard_expr
                if desired_guard != current_guard:
                    if current_guard is not None:
                        lines.append(f"        END IF")
                    if desired_guard is not None:
                        lines.append(f"        IF ({desired_guard}) THEN")
                    current_guard = desired_guard

                if a.copy_call:
                    # Registry Copy call (handles allocation internally)
                    # Replace loop variable with vit_alloc_i to avoid conflicts
                    copy_text = a.copy_call
                    loop_match = re.search(r'\bdo\s+(\w+)\s*=', copy_text, re.IGNORECASE)
                    if loop_match:
                        old_var = loop_match.group(1)
                        copy_text = re.sub(rf'\b{old_var}\b', 'vit_alloc_i', copy_text)
                    copy_text = re.sub(r'\bend\s+do\b', 'END DO',
                                       copy_text, flags=re.IGNORECASE)
                    for cl in copy_text.split("\n"):
                        lines.append(f"        {cl.strip()}")
                    err_msg = a.error_msg or f"Error in {a.source.split(':')[-1]}."
                    lines.append(f"            IF (ErrStat2 /= 0) THEN")
                    lines.append(f'                CALL SetErrStat(ErrID_Fatal, "{err_msg}", ErrStat, ErrMsg, RoutineName)')
                    lines.append(f"                RETURN")
                    lines.append(f"            END IF")
                else:
                    dims = ", ".join(a.size_exprs)
                    lines.append(f"        ALLOCATE({a.target_arg}%{a.field_name}({dims}), STAT=ErrStat2)")
                    err_msg = a.error_msg or f"Error allocating {a.target_arg}%{a.field_name}."
                    lines.append(f"        IF (ErrStat2 /= 0) THEN")
                    lines.append(f'            CALL SetErrStat(ErrID_Fatal, "{err_msg}", ErrStat, ErrMsg, RoutineName)')
                    lines.append(f"            RETURN")
                    lines.append(f"        END IF")
            if current_guard is not None:
                lines.append(f"        END IF")
        if unsafe_allocs:
            lines.append(f"        ! WARNING: These allocations could not be auto-extracted safely.")
            lines.append(f"        ! Review and add ALLOCATE statements manually if needed:")
            for a in unsafe_allocs:
                dims = ", ".join(a.size_exprs)
                lines.append(f"        !   {a.target_arg}%{a.field_name}({dims}) — local/computed size [{a.source}]")

    # View type executables: populator calls + stash assignments
    if view_args:
        lines.extend(_generate_view_executables(view_args, is_kernel))

    # CHARACTER copy loops (executable, before the C call)
    lines.extend(_generate_character_copy_loops(sig, kind_aliases, derived_types))

    # Allocate-on-return handshake variables
    lines.extend(_generate_alias_resolution(sig, kind_aliases, derived_types))
    lines.extend(_generate_logical_ref_prologue(sig, kind_aliases, derived_types))
    lines.extend(_generate_alloc_return_prologue(sig))

    # Build call with conversions (only non-passthrough args)
    call_args = _build_wrapper_call_args(sig, kind_aliases, derived_types)
    call_str = ", ".join(call_args)
    lines.append(f"        CALL {c_func_name}({call_str})")

    # Allocate-on-return: allocate the dummy, copy, free
    lines.extend(_generate_alloc_return_epilogue(sig))
    lines.extend(_generate_logical_ref_epilogue(sig, kind_aliases, derived_types))

    # Copy OPTIONAL INTENT(OUT/INOUT) values back to the actual arguments
    if optional_forwarded:
        for oarg in optional_forwarded:
            omapping = get_type_mapping(oarg.fortran_type, kind_aliases, derived_types)
            if oarg.intent in (IntentKind.OUT, IntentKind.INOUT):
                if not oarg.is_array and not (omapping.is_derived and omapping.is_c_compatible):
                    lines.append(f"        IF (PRESENT({oarg.name})) {oarg.name} = {oarg.name}_val")

    # Reverse CHARACTER copy: C_CHAR → CHARACTER for INTENT(OUT/INOUT)
    lines.extend(_generate_character_reverse_copy_loops(sig, kind_aliases, derived_types))

    # Reverse-copy: copy modified scalars from view back to Fortran type
    if reverse_copy and view_args:
        lines.append(f"        ! Copy modified scalars back from view to Fortran type")
        for arg, mapping in view_args:
            # Only reverse-copy INOUT args (not IN-only)
            if arg.intent and arg.intent.value.upper() in ("INOUT", "OUT"):
                type_lower = mapping.c_type.lower()
                if arg.is_array and not arg.is_assumed_shape and arg.array_dims:
                    lines.append(f"        DO vit_view_i = 1, {arg.array_dims}")
                    lines.append(f"            CALL vit_copy_scalars_to_{type_lower}({arg.name}_view(vit_view_i), {arg.name}(vit_view_i))")
                    lines.append(f"        END DO")
                else:
                    lines.append(f"        CALL vit_copy_scalars_to_{type_lower}({arg.name}_view, {arg.name})")

    lines.append(f"    END SUBROUTINE {sig.name}")
    return lines


def generate_vit_free_definition(sig) -> list:
    """Emit vit_free for a translation that uses allocate-on-return.

    Defined here rather than in a shared translation unit so that no build-system
    plumbing is required: several translated functions may each carry a copy, and
    the weak attribute lets the linker merge them. Fortran calls it, so C++ never
    ODR-uses it -- an ordinary inline function would be discarded before reaching
    the link.
    """
    if not alloc_return_args(sig):
        return []
    return [
        "// VIT allocate-on-return support. Frees a buffer that the translation",
        "// handed to the Fortran wrapper, using the allocator that made it.",
        "// Weak: several translations may each define it; the linker keeps one.",
        "#include <cstdlib>",
        'extern "C" {',
        "    __attribute__((weak)) void vit_free(void* vit_p) { std::free(vit_p); }",
        "}",
        "",
    ]


def is_alloc_return(arg) -> bool:
    """True if this dummy uses the ALLOCATE-ON-RETURN convention.

    An ``INTENT(OUT)`` ``ALLOCATABLE`` dummy arrives unallocated and the callee
    is what decides its extent -- often from data it has to read or compute
    first, so the extent cannot be known before the call. VIT's ordinary array
    convention passes SIZE(x) INTO the C function, which is undefined here, and
    the C side has no way to allocate a Fortran allocatable anyway.

    The convention instead is:

      * C receives ``T** x`` plus one ``int*`` per rank. It allocates with
        malloc, fills in Fortran (column-major) order, writes the extents, and
        sets ``*x``. If it does not allocate -- an error branch, say -- it
        leaves ``*x`` null and the extents 0.
      * The Fortran wrapper allocates the real dummy, copies, and frees.
        ``C_NULL_PTR`` means "callee did not allocate", and the dummy is left
        unallocated, which is what the Fortran did.

    INTENT(INOUT) ALLOCATABLE -- a dummy that is REallocated, growing an array
    that already has contents -- is deliberately NOT covered. That case has
    different semantics (the old contents matter) and usually a different answer
    entirely; see AddToList in the ROSCO replication log.
    """
    return (getattr(arg, "is_allocatable", False)
            and arg.intent == IntentKind.OUT
            and getattr(arg, "is_array", False))


def alloc_return_args(sig) -> list:
    """Every dummy of ``sig`` using the allocate-on-return convention."""
    return [a for a in sig.args if is_alloc_return(a)]


def _alloc_return_extent_names(arg) -> list[str]:
    """The C ``int*`` extent parameter names for an allocate-on-return arg."""
    if arg.array_rank <= 1:
        return [f"n_{arg.name}"]
    if arg.array_rank == 2:
        return [f"n_{arg.name}_rows", f"n_{arg.name}_cols"]
    raise ValueError(
        f"allocate-on-return supports rank 1 and 2; {arg.name} is rank {arg.array_rank}")


def _char_array_count_expr(arg) -> Optional[str]:
    """Element count for a CHARACTER *array* dummy, or None if it is a scalar.

    A CHARACTER(*) array dummy carries two independent sizes: the element
    length (LEN) and the number of elements (SIZE). The C++ side receives one
    flat buffer and needs both to index it, so the wrapper stages the array
    into a C_CHAR buffer of LEN*count. Explicit-shape dims are reproduced
    verbatim because they are usually other dummies (Words(NumWords));
    assumed-shape falls back to SIZE().
    """
    if not getattr(arg, "is_array", False):
        return None
    if getattr(arg, "is_assumed_shape", False) or not arg.array_dims:
        return f"SIZE({arg.name})"
    dims = [d.strip() for d in arg.array_dims.split(',')]
    return " * ".join(f"({d})" for d in dims)


def _get_char_len_expr(arg, mapping, sig):
    """Get the length expression for a CHARACTER argument, using original case."""
    if mapping.character_len_param:
        # CHARACTER(*) — assumed-length: use LEN(argname) at runtime
        if mapping.character_len_param == "*":
            return f"LEN({arg.name})"
        for a in sig.args:
            if a.name.lower() == mapping.character_len_param.lower():
                return a.name
        return mapping.character_len_param
    elif mapping.character_length and mapping.character_length > 1:
        return str(mapping.character_length)
    return None


def _generate_character_declarations(sig, kind_aliases, derived_types):
    """Emit local variable declarations for CHARACTER→C_CHAR conversion.
    Must be in the declaration section (before any executable statements)."""
    lines = []
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        len_expr = _get_char_len_expr(arg, mapping, sig)
        if len_expr:
            count = _char_array_count_expr(arg)
            if count:
                lines.append(f"        CHARACTER(KIND=C_CHAR) :: {arg.name}_c(({len_expr}) * ({count}))")
                lines.append(f"        INTEGER :: vit_i_{arg.name}, vit_j_{arg.name}")
            else:
                lines.append(f"        CHARACTER(KIND=C_CHAR) :: {arg.name}_c({len_expr})")
                lines.append(f"        INTEGER :: vit_i_{arg.name}")
    return lines


def _aliased_component_args(sig, kind_aliases=None, derived_types=None):
    """
    Find dummy arguments that may ALIAS a component of a view-type dummy.

    ROSCO's PIDController is the type case:

        PIDController(..., piP, reset, objInst, LocalVar)

    is called as ``PIDController(..., LocalVar%piP, ..., LocalVar)``. The
    wrapper copies LocalVar (including its nested piP) into LocalVar_view, hands
    the C++ a DIRECT pointer to the real LocalVar%piP, and then copies the STALE
    view back over LocalVar -- silently discarding every write the C++ made
    through the piP pointer. Lost update, and the returned value can still be
    correct, so it does not necessarily show up as a wrong answer.

    Whether the two actually alias is a property of the CALL SITE, which the
    wrapper cannot see. So this only identifies candidates statically -- a
    non-view derived-type dummy whose type appears as a component of a view-type
    dummy's type -- and the generated wrapper resolves it at RUNTIME by
    comparing addresses. That is exact for both callers: aliased ones route the
    pointer into the view, non-aliased ones keep the direct pointer.

    Returns a list of (arg, view_arg, component_name).
    """
    if not derived_types:
        return []

    # Use VIT's own collector rather than re-deriving view-ness: whether a type
    # is a view depends on vit.yaml's strategy, which is threaded through the
    # mapping and is NOT visible from the type name alone.
    view_args = _get_view_type_args(sig, kind_aliases, derived_types)
    if not view_args:
        return []

    plain_derived = []
    for a in sig.args:
        if not a.is_derived_type or a.is_array:
            continue
        m = get_type_mapping(a.fortran_type, kind_aliases, derived_types)
        if m.is_derived and m.is_c_compatible and not m.is_view_type:
            plain_derived.append(a)
    if not plain_derived:
        return []

    def _type_name(ft):
        u = ft.strip()
        if u.upper().startswith("TYPE(") and u.endswith(")"):
            return u[5:-1].strip()
        return u

    # The registry preserves the source's capitalisation ('piParams',
    # 'LocalVariables'), so look up case-insensitively.
    by_lower = {k.lower(): v for k, v in derived_types.items()}

    out = []
    for varg, _vm in view_args:
        if varg.is_array:
            continue
        info = by_lower.get(_type_name(varg.fortran_type).lower())
        if info is None or not getattr(info, "fields", None):
            continue
        for parg in plain_derived:
            ptype = _type_name(parg.fortran_type).lower()
            for f in info.fields:
                if f.is_array or getattr(f, "is_allocatable", False):
                    continue
                if _type_name(f.fortran_type).lower() == ptype:
                    out.append((parg, varg, f.name))
                    break
    return out


def _generate_alias_resolution(sig, kind_aliases=None, derived_types=None):
    """
    Emit the runtime aliasing check described in _aliased_component_args.

    Cheap: two C_LOC calls and a pointer compare, once per invocation.
    """
    pairs = _aliased_component_args(sig, kind_aliases, derived_types)
    if not pairs:
        return []
    lines = ["        ! Resolve aliasing: an argument that IS a component of a view-type",
             "        ! argument must be written through the VIEW, or the view copy-back",
             "        ! afterwards would discard those writes (see _aliased_component_args)."]
    for parg, varg, comp in pairs:
        lines.append(f"        IF (C_ASSOCIATED(C_LOC({parg.name}), C_LOC({varg.name}%{comp}))) THEN")
        lines.append(f"            {parg.name}_cptr = C_LOC({varg.name}_view%{comp})")
        lines.append(f"        ELSE")
        lines.append(f"            {parg.name}_cptr = C_LOC({parg.name})")
        lines.append(f"        END IF")
    return lines


def _alias_cptr_declarations(sig, kind_aliases=None, derived_types=None):
    """TYPE(C_PTR) locals holding the resolved pointer for each alias candidate."""
    pairs = _aliased_component_args(sig, kind_aliases, derived_types)
    return [f"        TYPE(C_PTR) :: {parg.name}_cptr" for parg, _v, _c in pairs]


def _logical_ref_args(sig, kind_aliases, derived_types):
    """INTENT(OUT)/INTENT(INOUT) LOGICAL scalars, which cross as INTEGER(C_INT).

    type_map.py sends a Fortran LOGICAL across the boundary as INTEGER(C_INT):
    the right memory layout, and NOT assignment-compatible in Fortran. Every
    other direction of that conversion is already handled -- passing a LOGICAL
    by value (`e72235f`), converting one back inside a kernel callee bridge
    (`05b70bc`), and test_validate's bridge (`ece0c3d`) -- but an INTENT(OUT)
    scalar took the earlier "INOUT/OUT scalars passed by reference (no
    conversion needed)" branch in _build_wrapper_call_args and went straight
    through, which gfortran rejects:

        Error: Type mismatch in argument 'foundline'; passed LOGICAL(4) to INTEGER(4)

    A by-reference argument cannot be converted in the call itself, so it needs
    a staging INTEGER(C_INT) local: seeded from the LOGICAL for INOUT, passed
    to C, and copied back with (/= 0) afterwards.

    OPTIONAL args are excluded -- they are already staged through
    <name>_val by _generate_optional_preamble.
    """
    out = []
    for arg in sig.args:
        if arg.intent not in (IntentKind.OUT, IntentKind.INOUT):
            continue
        if arg.is_array or arg.is_derived_type or arg.is_optional:
            continue
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        if (mapping.fortran_type.upper().lstrip().startswith("LOGICAL")
                and mapping.iso_c_type.startswith("INTEGER")):
            out.append((arg, mapping))
    return out


def _logical_ref_declarations(sig, kind_aliases, derived_types):
    """Staging INTEGER(C_INT) locals for by-reference LOGICAL arguments."""
    return [f"        INTEGER({m.c_kind}) :: {a.name}_lgc"
            for a, m in _logical_ref_args(sig, kind_aliases, derived_types)]


def _generate_logical_ref_prologue(sig, kind_aliases, derived_types):
    """Seed the staging locals. INTENT(OUT) has no incoming value to seed."""
    lines = []
    for arg, mapping in _logical_ref_args(sig, kind_aliases, derived_types):
        if arg.intent == IntentKind.INOUT:
            lines.append(f"        {arg.name}_lgc = MERGE(1_{mapping.c_kind}, "
                         f"0_{mapping.c_kind}, {arg.name})")
        else:
            lines.append(f"        {arg.name}_lgc = 0")
    return lines


def _generate_logical_ref_epilogue(sig, kind_aliases, derived_types):
    """Copy the staging locals back into the LOGICAL arguments."""
    lines = []
    for arg, _m in _logical_ref_args(sig, kind_aliases, derived_types):
        lines.append(f"        {arg.name} = ({arg.name}_lgc /= 0)")
    return lines


def _generate_character_copy_loops(sig, kind_aliases, derived_types):
    """Emit copy loops for CHARACTER→C_CHAR conversion.
    Must be in the executable section (before the C call)."""
    lines = []
    has_any = False
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        len_expr = _get_char_len_expr(arg, mapping, sig)
        if len_expr:
            if not has_any:
                lines.append(f"        ! Convert CHARACTER args to C_CHAR arrays")
                has_any = True
            count = _char_array_count_expr(arg)
            if count:
                lines.append(f"        DO vit_j_{arg.name} = 1, {count}")
                lines.append(f"            DO vit_i_{arg.name} = 1, {len_expr}")
                lines.append(f"                {arg.name}_c((vit_j_{arg.name} - 1) * ({len_expr}) + vit_i_{arg.name}) = &")
                lines.append(f"                    {arg.name}(vit_j_{arg.name})(vit_i_{arg.name}:vit_i_{arg.name})")
                lines.append(f"            END DO")
                lines.append(f"        END DO")
            else:
                lines.append(f"        DO vit_i_{arg.name} = 1, {len_expr}")
                lines.append(f"            {arg.name}_c(vit_i_{arg.name}) = {arg.name}(vit_i_{arg.name}:vit_i_{arg.name})")
                lines.append(f"        END DO")
    return lines


def _generate_character_reverse_copy_loops(sig, kind_aliases, derived_types):
    """Emit reverse copy loops for C_CHAR→CHARACTER conversion.
    Must be in the executable section (after the C call).
    Only for INTENT(OUT) and INTENT(INOUT) CHARACTER parameters."""
    lines = []
    has_any = False
    for arg in sig.args:
        intent_str = arg.intent.value.upper() if arg.intent else ""
        if intent_str not in ("OUT", "INOUT"):
            continue
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        len_expr = _get_char_len_expr(arg, mapping, sig)
        if len_expr:
            if not has_any:
                lines.append(f"        ! Copy C_CHAR arrays back to CHARACTER args (INTENT OUT/INOUT)")
                has_any = True
            count = _char_array_count_expr(arg)
            if count:
                lines.append(f"        DO vit_j_{arg.name} = 1, {count}")
                lines.append(f"            DO vit_i_{arg.name} = 1, {len_expr}")
                lines.append(f"                {arg.name}(vit_j_{arg.name})(vit_i_{arg.name}:vit_i_{arg.name}) = &")
                lines.append(f"                    {arg.name}_c((vit_j_{arg.name} - 1) * ({len_expr}) + vit_i_{arg.name})")
                lines.append(f"            END DO")
                lines.append(f"        END DO")
            else:
                lines.append(f"        DO vit_i_{arg.name} = 1, {len_expr}")
                lines.append(f"            {arg.name}(vit_i_{arg.name}:vit_i_{arg.name}) = {arg.name}_c(vit_i_{arg.name})")
                lines.append(f"        END DO")
    return lines


def _generate_alloc_return_declarations(sig, kind_aliases):
    """Locals and the vit_free interface for allocate-on-return args.

    The vit_free interface is emitted INSIDE the wrapper rather than at module
    level on purpose: two translated functions in the same module would
    otherwise each contribute a vit_free interface and collide.
    """
    allocs = alloc_return_args(sig)
    if not allocs:
        return []
    lines = [
        "        ! VIT allocate-on-return: the C++ side discovers the extent,",
        "        ! allocates, and hands back a pointer; the wrapper copies into the",
        "        ! Fortran ALLOCATABLE and frees. C_NULL_PTR means 'not allocated'.",
        "        INTERFACE",
        "            SUBROUTINE vit_free(vit_p) BIND(C, NAME='vit_free')",
        "                USE ISO_C_BINDING",
        "                TYPE(C_PTR), VALUE :: vit_p",
        "            END SUBROUTINE vit_free",
        "        END INTERFACE",
    ]
    for arg in allocs:
        resolved = _resolve_fortran_type(arg.fortran_type, kind_aliases)
        dims = ",".join(":" for _ in range(max(1, arg.array_rank)))
        lines.append(f"        TYPE(C_PTR) :: {arg.name}_cptr")
        for n in _alloc_return_extent_names(arg):
            lines.append(f"        INTEGER(C_INT) :: {n}")
        lines.append(f"        {resolved}, POINTER :: {arg.name}_fptr({dims})")
    return lines


def _generate_alloc_return_prologue(sig):
    """Initialise the handshake variables before the C call."""
    allocs = alloc_return_args(sig)
    if not allocs:
        return []
    lines = []
    for arg in allocs:
        lines.append(f"        {arg.name}_cptr = C_NULL_PTR")
        for n in _alloc_return_extent_names(arg):
            lines.append(f"        {n} = 0")
    return lines


def _generate_alloc_return_epilogue(sig):
    """Allocate the real dummy from what the C side returned, copy, free."""
    allocs = alloc_return_args(sig)
    if not allocs:
        return []
    lines = []
    for arg in allocs:
        extents = _alloc_return_extent_names(arg)
        shape = ", ".join(extents)
        lines.append(f"        IF (C_ASSOCIATED({arg.name}_cptr)) THEN")
        lines.append(f"            CALL C_F_POINTER({arg.name}_cptr, {arg.name}_fptr, [{shape}])")
        lines.append(f"            ALLOCATE({arg.name}({shape}))")
        lines.append(f"            {arg.name} = {arg.name}_fptr")
        lines.append(f"            CALL vit_free({arg.name}_cptr)")
        lines.append(f"        END IF")
    return lines


def _get_view_type_args(sig: FortranSignature, kind_aliases, derived_types) -> list[tuple]:
    """
    Identify args that use the view type pattern.

    Returns list of (arg, mapping) tuples for view-type args.
    """
    result = []
    for arg in sig.args:
        if not arg.is_derived_type:
            continue
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        if mapping.is_view_type:
            result.append((arg, mapping))
    return result


def _generate_view_preamble(view_args: list[tuple], is_kernel: bool = False) -> list[str]:
    """
    Generate USE statements, local declarations, and populator calls
    for view-type arguments.

    Returns all lines (declarations + executables) for callers that don't
    need to interleave other declarations between them. For callers that do,
    use _generate_view_declarations() and _generate_view_executables().
    """
    if not view_args:
        return []
    decls = _generate_view_declarations(view_args)
    execs = _generate_view_executables(view_args, is_kernel)
    return decls + execs


def _generate_view_declarations(view_args: list[tuple]) -> list[str]:
    """Generate local TYPE declarations for view-type arguments."""
    if not view_args:
        return []
    lines = []
    need_loop_var = False
    for arg, mapping in view_args:
        type_lower = mapping.c_type.lower()
        view_type = f"{type_lower}_view_t"
        if arg.is_array and not arg.is_assumed_shape and arg.array_dims:
            lines.append(f"        TYPE({view_type}), TARGET :: {arg.name}_view({arg.array_dims})")
            need_loop_var = True
        else:
            lines.append(f"        TYPE({view_type}), TARGET :: {arg.name}_view")
    if need_loop_var:
        lines.append(f"        INTEGER :: vit_view_i")
    return lines


def _generate_view_executables(view_args: list[tuple], is_kernel: bool = False) -> list[str]:
    """Generate populator calls and stash assignments for view-type arguments."""
    if not view_args:
        return []
    lines = []
    lines.append(f"        ! Populate view structs from Fortran types")
    for arg, mapping in view_args:
        type_lower = mapping.c_type.lower()
        if arg.is_array and not arg.is_assumed_shape and arg.array_dims:
            lines.append(f"        DO vit_view_i = 1, {arg.array_dims}")
            lines.append(f"            CALL vit_populate_{type_lower}({arg.name}(vit_view_i), {arg.name}_view(vit_view_i))")
            lines.append(f"        END DO")
        else:
            lines.append(f"        CALL vit_populate_{type_lower}({arg.name}, {arg.name}_view)")

    if is_kernel:
        lines.append(f"        ! Stash original Fortran pointers for callee bridges")
        for arg, mapping in view_args:
            type_lower = mapping.c_type.lower()
            stash_name = f"vit_original_{type_lower}"
            if arg.is_array and not arg.is_assumed_shape and arg.array_dims:
                lines.append(f"        {stash_name} => {arg.name}(1)")
            else:
                lines.append(f"        {stash_name} => {arg.name}")

    return lines


def _get_view_use_statements(view_args: list[tuple], is_kernel: bool = False,
                             reverse_copy: bool = False) -> list[str]:
    """Generate USE statements for view type modules."""
    lines = []
    seen = set()
    for arg, mapping in view_args:
        type_lower = mapping.c_type.lower()
        module_name = f"vit_{type_lower}_view"
        if module_name not in seen:
            only_list = f"{type_lower}_view_t, vit_populate_{type_lower}"
            if is_kernel:
                stash_name = f"vit_original_{type_lower}"
                only_list += f", {stash_name}"
            if reverse_copy:
                only_list += f", vit_copy_scalars_to_{type_lower}"
            lines.append(
                f"        USE {module_name}, ONLY: {only_list}"
            )
            seen.add(module_name)
    return lines


def _get_target_attr(arg: FortranArg, kind_aliases, derived_types) -> str:
    """Return ', TARGET' if the arg is a C-compatible derived type, else ''."""
    if arg.is_derived_type:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        if mapping.is_derived and mapping.is_c_compatible:
            return ", TARGET"
    return ""


def _generate_optional_preamble(optional_args, kind_aliases, derived_types):
    """
    Generate local variable declarations and PRESENT() checks for OPTIONAL args.

    For each OPTIONAL arg, the wrapper gets:
    - INTEGER(C_INT) :: has_<name>_flag   (0 or 1)
    - <iso_c_type> :: <name>_val          (value or default)
    - IF (PRESENT(<name>)) THEN ... END IF
    """
    lines = []
    lines.append("")
    lines.append(f"        ! Local variables for OPTIONAL args")

    # Declare local variables
    for oarg in optional_args:
        omapping = get_type_mapping(oarg.fortran_type, kind_aliases, derived_types)
        lines.append(f"        INTEGER(C_INT) :: has_{oarg.name}_flag")
        if not oarg.is_array and not (omapping.is_derived and omapping.is_c_compatible):
            lines.append(f"        {omapping.iso_c_type} :: {oarg.name}_val")

    lines.append("")

    # Initialize and set from PRESENT()
    for oarg in optional_args:
        omapping = get_type_mapping(oarg.fortran_type, kind_aliases, derived_types)
        lines.append(f"        has_{oarg.name}_flag = 0")
        if not oarg.is_array and not (omapping.is_derived and omapping.is_c_compatible):
            if omapping.iso_c_type.startswith("REAL"):
                lines.append(f"        {oarg.name}_val = 0.0D0")
            else:
                lines.append(f"        {oarg.name}_val = 0")
        lines.append(f"        IF (PRESENT({oarg.name})) THEN")
        lines.append(f"            has_{oarg.name}_flag = 1")
        if not oarg.is_array and not (omapping.is_derived and omapping.is_c_compatible):
            if "LOGICAL" in oarg.fortran_type.upper():
                # A LOGICAL crosses as INTEGER(C_INT), and `int_val = logical`
                # is NOT standard Fortran -- gfortran accepts it as an
                # extension, warning only, so it built and was correct, and the
                # non-standard emission was written down as a translation tip
                # ("if a build ever rejects it, this is the reason") instead of
                # being fixed. The non-optional path has used MERGE since
                # `e72235f`; this is the same conversion, and a campaign on ifx
                # or flang should not be the thing that discovers the
                # difference.
                lines.append(f"            {oarg.name}_val = "
                             f"MERGE(1_C_INT, 0_C_INT, {oarg.name})")
            # Apply kind conversion if needed
            elif omapping.c_kind != omapping.fortran_kind and omapping.fortran_kind:
                if omapping.iso_c_type.startswith("REAL"):
                    lines.append(f"            {oarg.name}_val = REAL({oarg.name}, {omapping.c_kind})")
                elif omapping.iso_c_type.startswith("INTEGER"):
                    lines.append(f"            {oarg.name}_val = INT({oarg.name}, {omapping.c_kind})")
                else:
                    lines.append(f"            {oarg.name}_val = {oarg.name}")
            else:
                lines.append(f"            {oarg.name}_val = {oarg.name}")
        lines.append(f"        END IF")

    return lines


# --- Internal helpers ---

def _get_return_type_mapping(sig: FortranSignature,
                             kind_aliases: Optional[dict] = None,
                             derived_types: Optional[dict] = None) -> TypeMapping:
    """Get the type mapping for a function's return type."""
    if sig.result_type:
        return get_type_mapping(sig.result_type, kind_aliases, derived_types)
    # Fallback: try to infer from result variable name or first arg
    # This is a heuristic — explicit RESULT type is preferred
    return get_type_mapping("REAL(8)", kind_aliases, derived_types)


def result_is_out_param(sig: FortranSignature,
                        kind_aliases: Optional[dict] = None,
                        derived_types: Optional[dict] = None) -> bool:
    """
    True when a FUNCTION's result cannot be a C return value and must instead
    be written through an output parameter.

    Two cases: array-valued results, and CHARACTER(n) results with n > 1. A
    CHARACTER(1) result is a single byte and still returns by value.

    Fortran CHARACTER results are fixed-width and blank-padded, so they behave
    exactly like the array case -- the caller owns the buffer and the callee
    fills it. Returning `char` instead (which is what VIT did before this
    existed) silently truncates the result to its first byte.
    """
    if not sig.is_function:
        return False
    if sig.result_is_array:
        return True
    if sig.result_type:
        mapping = get_type_mapping(sig.result_type, kind_aliases, derived_types)
        if mapping.character_len_param:
            return True
        if mapping.character_length and mapping.character_length > 1:
            return True
    return False


def result_char_len(sig: FortranSignature,
                    kind_aliases: Optional[dict] = None,
                    derived_types: Optional[dict] = None) -> Optional[int]:
    """Declared length of a CHARACTER function result, or None."""
    if not sig.is_function or sig.result_is_array or not sig.result_type:
        return None
    mapping = get_type_mapping(sig.result_type, kind_aliases, derived_types)
    if mapping.character_length and mapping.character_length > 1:
        return mapping.character_length
    return None


def dropped_derived_args(sig: FortranSignature,
                         kind_aliases: Optional[dict] = None,
                         derived_types: Optional[dict] = None) -> list[tuple[str, str, str]]:
    """The derived-type arguments `build_c_params` omits, and why.

    Returns `(argument, TYPE(...), reason)`. A dropped argument is invisible in
    the output of `build_c_params` -- the list simply has one fewer entry -- so
    any caller that needs the call to MATCH something else (a bridge, a
    translation, a hand-written declaration) has to be able to ask.

    The reason is not decoration. `is_c_compatible` is False if ANY field is
    ALLOCATABLE, POINTER, or a nested TYPE, so "not C-compatible" spans a type
    that cannot cross at all and one that needs `strategy: view` in `vit.yaml`
    and would then cross fine. ROSCO's `LocalVariables` is the second: 168
    fields, one of them `CHARACTER, DIMENSION(:), ALLOCATABLE`, and configuring
    the view strategy makes it cross whole.
    """
    out: list[tuple[str, str, str]] = []
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)
        if not (mapping.is_derived and not mapping.is_c_compatible):
            continue
        info = None
        if derived_types:
            for k, v in derived_types.items():
                if k.upper() == (arg.derived_type_name or "").upper():
                    info = v
                    break
        if info is None:
            reason = ("no entry in the derived-type registry, so nothing is known "
                      "about its fields")
        else:
            blockers = []
            if any(f.is_allocatable for f in info.fields):
                blockers.append("ALLOCATABLE field(s)")
            if any(f.is_pointer for f in info.fields):
                blockers.append("POINTER field(s)")
            if any(f.fortran_type.upper().startswith("TYPE(") for f in info.fields):
                blockers.append("nested derived-type field(s)")
            reason = (", ".join(blockers) or "not C-compatible") + \
                     "; set `strategy: view` for this type in vit.yaml to cross it"
        out.append((arg.name, arg.fortran_type, reason))
    return out


def build_c_params(sig: FortranSignature,
                    kind_aliases: Optional[dict] = None,
                    derived_types: Optional[dict] = None) -> list[tuple[str, str]]:
    """
    Build the C parameter list: [(c_type, param_name), ...]

    Skips passthrough args. Adds size params for assumed-shape arrays.
    For array-valued function results, appends a result output pointer.
    C-compatible derived types become struct pointers.
    OPTIONAL args become flag + value pairs.
    Scalar INTENT(OUT/INOUT) args are always pointers.
    """
    params = []
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)

        # Skip passthrough args (non-C-compatible derived types).
        #
        # This `continue` is silent, and `is_c_compatible` is a single boolean
        # that two generators read to mean opposite things: here it means "omit
        # the argument", while `test_validate._has_allocatable_fields` reads the
        # same False to mean "decompose it into one bridge parameter per field".
        # The two then emit a C++ declaration and a Fortran bridge that disagree
        # about the function's arity, and the symptom is a link or compile error
        # naming neither cause.
        #
        # It stays a skip, because a genuine passthrough must keep being
        # skipped and nothing in the type model distinguishes "deliberately not
        # crossed" from "no strategy configured yet". What it no longer does is
        # happen quietly: `dropped_derived_args` reports it, and
        # `test_validate` refuses to emit a skeleton whose bridge needs an
        # argument the C++ call does not have.
        if mapping.is_derived and not mapping.is_c_compatible:
            continue

        # OPTIONAL args: emit flag (int) + value pair
        if arg.is_optional:
            params.append(("int", f"has_{arg.name}"))
            if mapping.is_derived and mapping.is_c_compatible:
                suffix = "_view_t" if mapping.is_view_type else "_t"
                params.append((f"{mapping.c_type.lower()}{suffix}*", arg.name))
                if arg.is_array and arg.is_assumed_shape:
                    if arg.array_rank == 1:
                        params.append(("int", f"n_{arg.name}"))
                    elif arg.array_rank == 2:
                        params.append(("int", f"n_{arg.name}_rows"))
                        params.append(("int", f"n_{arg.name}_cols"))
            elif arg.is_array:
                params.append((f"{mapping.c_type}*", arg.name))
                if arg.is_assumed_shape:
                    if arg.array_rank == 1:
                        params.append(("int", f"n_{arg.name}"))
                    elif arg.array_rank == 2:
                        params.append(("int", f"n_{arg.name}_rows"))
                        params.append(("int", f"n_{arg.name}_cols"))
                    else:
                        raise ValueError(f"Unsupported array rank {arg.array_rank} for {arg.name}")
            else:
                if arg.intent in (IntentKind.OUT, IntentKind.INOUT):
                    params.append((f"{mapping.c_type}*", arg.name))
                else:
                    params.append((mapping.c_type, arg.name))
            continue

        # C-compatible derived type → struct pointer
        if mapping.is_derived and mapping.is_c_compatible:
            suffix = "_view_t" if mapping.is_view_type else "_t"
            params.append((f"{mapping.c_type.lower()}{suffix}*", arg.name))
            if arg.is_array:
                if arg.array_rank == 1:
                    params.append(("int", f"n_{arg.name}"))
                elif arg.array_rank == 2:
                    params.append(("int", f"n_{arg.name}_rows"))
                    params.append(("int", f"n_{arg.name}_cols"))
            continue

        if is_alloc_return(arg):
            # Allocate-on-return: pointer-to-pointer plus one extent OUT param
            # per rank. See is_alloc_return for the contract.
            params.append((f"{mapping.c_type}**", arg.name))
            for n in _alloc_return_extent_names(arg):
                params.append(("int*", n))
            continue

        if arg.is_array:
            params.append((f"{mapping.c_type}*", arg.name))
            # Add size parameter(s) for assumed-shape arrays
            if arg.is_assumed_shape:
                if arg.array_rank == 1:
                    params.append(("int", f"n_{arg.name}"))
                elif arg.array_rank == 2:
                    params.append(("int", f"n_{arg.name}_rows"))
                    params.append(("int", f"n_{arg.name}_cols"))
                else:
                    raise ValueError(f"Unsupported array rank {arg.array_rank} for {arg.name}")
            # A CHARACTER(*) ARRAY carries two independent sizes. The element
            # count comes from the dims above (or is already another dummy);
            # the element LENGTH is what the C++ side strides by, and without
            # it the flat buffer cannot be indexed at all.
            if mapping.character_len_param == "*":
                params.append(("int", f"len_{arg.name}"))
        else:
            # CHARACTER with fixed length > 1 or parameterized length → always pointer
            if (mapping.character_length and mapping.character_length > 1) or mapping.character_len_param:
                params.append((f"{mapping.c_type}*", arg.name))
                # Assumed-length CHARACTER(*) carries no length the C++ side can
                # recover: the buffer is blank-padded, not NUL-terminated, and
                # the length is a runtime property of the caller's actual
                # argument. Pass it explicitly, exactly as an assumed-shape array
                # passes SIZE. A parameterized length -- CHARACTER(n) where n is
                # another dummy -- needs nothing extra, since n is already a
                # parameter.
                if mapping.character_len_param == "*":
                    params.append(("int", f"len_{arg.name}"))
            # Scalar INTENT(OUT/INOUT) args must be pointers —
            # the Fortran BIND(C) interface passes them by reference (no VALUE).
            # This applies to both functions and subroutines.
            elif arg.intent in (IntentKind.OUT, IntentKind.INOUT):
                params.append((f"{mapping.c_type}*", arg.name))
            else:
                params.append((mapping.c_type, arg.name))

    # Array- and CHARACTER-valued function results become an output pointer
    # parameter. The C function returns void; the result is written through it.
    if result_is_out_param(sig, kind_aliases, derived_types):
        ret_mapping = _get_return_type_mapping(sig, kind_aliases, derived_types)
        result_param_name = f"{sig.name}_result"
        params.append((f"{ret_mapping.c_type}*", result_param_name))

    return params


def _build_interface_args(sig: FortranSignature,
                          kind_aliases: Optional[dict] = None,
                          derived_types: Optional[dict] = None) -> list[dict]:
    """
    Build the interface argument list for the BIND(C) interface.

    Returns list of dicts with:
      - iface_name: arg name in the interface
      - iface_decl: full Fortran declaration line

    Skips passthrough args. Adds size params for assumed-shape arrays.
    Converts assumed-shape (:) to assumed-size (*).
    C-compatible derived types become TYPE(C_PTR), VALUE.
    OPTIONAL args become flag + value pairs (both non-OPTIONAL).
    Scalar INTENT(OUT/INOUT) args are always by-reference.
    """
    args = []
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)

        # Skip passthrough args
        if mapping.is_derived and not mapping.is_c_compatible:
            continue

        # OPTIONAL args: flag (INTEGER(C_INT), VALUE) + value
        if arg.is_optional:
            args.append({
                "iface_name": f"has_{arg.name}",
                "iface_decl": f"INTEGER(C_INT), VALUE :: has_{arg.name}",
            })
            if mapping.is_derived and mapping.is_c_compatible:
                args.append({
                    "iface_name": arg.name,
                    "iface_decl": f"TYPE(C_PTR), VALUE :: {arg.name}",
                })
                if arg.is_array and arg.is_assumed_shape:
                    if arg.array_rank == 1:
                        args.append({
                            "iface_name": f"n_{arg.name}",
                            "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}",
                        })
                    elif arg.array_rank == 2:
                        args.append({
                            "iface_name": f"n_{arg.name}_rows",
                            "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}_rows",
                        })
                        args.append({
                            "iface_name": f"n_{arg.name}_cols",
                            "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}_cols",
                        })
            elif arg.is_array:
                intent_str = arg.intent.value or "IN"
                args.append({
                    "iface_name": arg.name,
                    "iface_decl": f"{mapping.iso_c_type}, INTENT({intent_str}) :: {arg.name}(*)",
                })
                if arg.is_assumed_shape:
                    if arg.array_rank == 1:
                        args.append({
                            "iface_name": f"n_{arg.name}",
                            "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}",
                        })
                    elif arg.array_rank == 2:
                        args.append({
                            "iface_name": f"n_{arg.name}_rows",
                            "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}_rows",
                        })
                        args.append({
                            "iface_name": f"n_{arg.name}_cols",
                            "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}_cols",
                        })
            else:
                if arg.intent in (IntentKind.OUT, IntentKind.INOUT):
                    intent_str = arg.intent.value
                    args.append({
                        "iface_name": arg.name,
                        "iface_decl": f"{mapping.iso_c_type}, INTENT({intent_str}) :: {arg.name}",
                    })
                else:
                    args.append({
                        "iface_name": arg.name,
                        "iface_decl": f"{mapping.iso_c_type}, VALUE :: {arg.name}",
                    })
            continue

        # C-compatible derived type → TYPE(C_PTR), VALUE
        if mapping.is_derived and mapping.is_c_compatible:
            args.append({
                "iface_name": arg.name,
                "iface_decl": f"TYPE(C_PTR), VALUE :: {arg.name}",
            })
            if arg.is_array:
                if arg.array_rank == 1:
                    args.append({
                        "iface_name": f"n_{arg.name}",
                        "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}",
                    })
                elif arg.array_rank == 2:
                    args.append({
                        "iface_name": f"n_{arg.name}_rows",
                        "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}_rows",
                    })
                    args.append({
                        "iface_name": f"n_{arg.name}_cols",
                        "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}_cols",
                    })
            continue

        if is_alloc_return(arg):
            args.append({
                "iface_name": f"{arg.name}_cptr",
                "iface_decl": f"TYPE(C_PTR), INTENT(OUT) :: {arg.name}_cptr",
            })
            for n in _alloc_return_extent_names(arg):
                args.append({
                    "iface_name": n,
                    "iface_decl": f"INTEGER(C_INT), INTENT(OUT) :: {n}",
                })
            continue

        if arg.is_array:
            intent_str = arg.intent.value or "IN"
            if not arg.intent.value:
                intent_str = "INOUT" if sig.is_subroutine else "IN"
            # Use assumed-size (*) for BIND(C) interface
            args.append({
                "iface_name": arg.name,
                "iface_decl": f"{mapping.iso_c_type}, INTENT({intent_str}) :: {arg.name}(*)",
            })
            # Add size parameter(s) for assumed-shape arrays
            if arg.is_assumed_shape:
                if arg.array_rank == 1:
                    args.append({
                        "iface_name": f"n_{arg.name}",
                        "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}",
                    })
                elif arg.array_rank == 2:
                    args.append({
                        "iface_name": f"n_{arg.name}_rows",
                        "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}_rows",
                    })
                    args.append({
                        "iface_name": f"n_{arg.name}_cols",
                        "iface_decl": f"INTEGER(C_INT), VALUE :: n_{arg.name}_cols",
                    })
            # See build_c_params: a CHARACTER(*) array passes its element length.
            if mapping.character_len_param == "*":
                args.append({
                    "iface_name": f"len_{arg.name}",
                    "iface_decl": f"INTEGER(C_INT), VALUE :: len_{arg.name}",
                })
        else:
            # CHARACTER with fixed length > 1 or parameterized length → assumed-size array
            if (mapping.character_length and mapping.character_length > 1) or mapping.character_len_param:
                intent_str = arg.intent.value or "IN"
                args.append({
                    "iface_name": arg.name,
                    "iface_decl": f"CHARACTER(KIND=C_CHAR), INTENT({intent_str}) :: {arg.name}(*)",
                })
                # See build_c_params: assumed-length needs an explicit length.
                if mapping.character_len_param == "*":
                    args.append({
                        "iface_name": f"len_{arg.name}",
                        "iface_decl": f"INTEGER(C_INT), VALUE :: len_{arg.name}",
                    })
            # Scalar INTENT(OUT/INOUT) → by reference (no VALUE)
            elif arg.intent in (IntentKind.OUT, IntentKind.INOUT):
                intent_str = arg.intent.value
                args.append({
                    "iface_name": arg.name,
                    "iface_decl": f"{mapping.iso_c_type}, INTENT({intent_str}) :: {arg.name}",
                })
            else:
                # Scalars passed by VALUE
                args.append({
                    "iface_name": arg.name,
                    "iface_decl": f"{mapping.iso_c_type}, VALUE :: {arg.name}",
                })

    # Array- and CHARACTER-valued function results become an INTENT(OUT)
    # assumed-size parameter. For CHARACTER the element type is C_CHAR, so the
    # Fortran side passes a CHARACTER(KIND=C_CHAR) buffer, not the result
    # variable itself.
    if result_is_out_param(sig, kind_aliases, derived_types):
        ret_mapping = _get_return_type_mapping(sig, kind_aliases, derived_types)
        result_param_name = f"{sig.name}_result"
        if result_char_len(sig, kind_aliases, derived_types):
            iface_decl = f"CHARACTER(KIND=C_CHAR), INTENT(OUT) :: {result_param_name}(*)"
        else:
            iface_decl = f"{ret_mapping.iso_c_type}, INTENT(OUT) :: {result_param_name}(*)"
        args.append({
            "iface_name": result_param_name,
            "iface_decl": iface_decl,
        })

    return args


def _build_wrapper_call_args(sig: FortranSignature,
                             kind_aliases: Optional[dict] = None,
                             derived_types: Optional[dict] = None) -> list[str]:
    """
    Build the argument list for the C function call inside the Fortran wrapper.

    Skips passthrough args. Adds SIZE(array) for assumed-shape arrays.
    Handles type conversions for kind mismatches.
    C-compatible derived types use C_LOC().
    OPTIONAL args use local flag/value variables.
    LOGICAL args get explicit conversion to C_BOOL.
    """
    call_args = []
    _alias_names = {a.name for a, _v, _c in _aliased_component_args(sig, kind_aliases, derived_types)}
    for arg in sig.args:
        mapping = get_type_mapping(arg.fortran_type, kind_aliases, derived_types)

        # Skip passthrough args
        if mapping.is_derived and not mapping.is_c_compatible:
            continue

        # OPTIONAL args: pass local flag and value variables
        if arg.is_optional:
            call_args.append(f"has_{arg.name}_flag")
            if mapping.is_derived and mapping.is_c_compatible:
                if arg.is_array:
                    if mapping.is_view_type:
                        call_args.append(f"C_LOC({arg.name}_view(1))")
                    else:
                        call_args.append(f"C_LOC({arg.name}(1))")
                    if arg.is_assumed_shape:
                        if arg.array_rank == 1:
                            call_args.append(f"SIZE({arg.name})")
                        elif arg.array_rank == 2:
                            call_args.append(f"SIZE({arg.name}, 1)")
                            call_args.append(f"SIZE({arg.name}, 2)")
                elif mapping.is_view_type:
                    call_args.append(f"C_LOC({arg.name}_view)")
                else:
                    call_args.append(f"C_LOC({arg.name})")
            elif arg.is_array:
                call_args.append(arg.name)
                if arg.is_assumed_shape:
                    if arg.array_rank == 1:
                        call_args.append(f"SIZE({arg.name})")
                    elif arg.array_rank == 2:
                        call_args.append(f"SIZE({arg.name}, 1)")
                        call_args.append(f"SIZE({arg.name}, 2)")
            else:
                call_args.append(f"{arg.name}_val")
            continue

        # C-compatible derived type → C_LOC()
        if mapping.is_derived and mapping.is_c_compatible:
            if arg.is_array:
                if mapping.is_view_type:
                    call_args.append(f"C_LOC({arg.name}_view(1))")
                else:
                    call_args.append(f"C_LOC({arg.name}(1))")
                if arg.is_assumed_shape:
                    if arg.array_rank == 1:
                        call_args.append(f"SIZE({arg.name})")
                    elif arg.array_rank == 2:
                        call_args.append(f"SIZE({arg.name}, 1)")
                        call_args.append(f"SIZE({arg.name}, 2)")
                elif arg.is_array:
                    dims = [d.strip() for d in arg.array_dims.split(',')]
                    for d in dims:
                        call_args.append(d)
            elif mapping.is_view_type:
                call_args.append(f"C_LOC({arg.name}_view)")
            elif arg.name in _alias_names:
                # May be a component of a view arg; the wrapper resolved which
                # storage to write through at runtime.
                call_args.append(f"{arg.name}_cptr")
            else:
                call_args.append(f"C_LOC({arg.name})")
            continue

        if is_alloc_return(arg):
            call_args.append(f"{arg.name}_cptr")
            call_args.extend(_alloc_return_extent_names(arg))
            continue

        if arg.is_array:
            # CHARACTER arrays go through the same C_CHAR staging buffer as
            # CHARACTER scalars: a CHARACTER(n) array cannot be sequence-
            # associated with a BIND(C) CHARACTER(KIND=C_CHAR) dummy.
            if _get_char_len_expr(arg, mapping, sig):
                call_args.append(f"{arg.name}_c")
            else:
                # Arrays are passed by reference
                call_args.append(arg.name)
            # Pass SIZE for assumed-shape arrays
            if arg.is_assumed_shape:
                if arg.array_rank == 1:
                    call_args.append(f"SIZE({arg.name})")
                elif arg.array_rank == 2:
                    call_args.append(f"SIZE({arg.name}, 1)")
                    call_args.append(f"SIZE({arg.name}, 2)")
            if mapping.character_len_param == "*":
                call_args.append(f"LEN({arg.name})")
        elif (mapping.character_length and mapping.character_length > 1) or mapping.character_len_param:
            # CHARACTER with fixed/parameterized length: pass local C_CHAR array
            call_args.append(f"{arg.name}_c")
            # See build_c_params: assumed-length also passes its length.
            if mapping.character_len_param == "*":
                call_args.append(f"LEN({arg.name})")
        elif (arg.intent in (IntentKind.OUT, IntentKind.INOUT)
                and not arg.is_array and not arg.is_derived_type
                and not arg.is_optional
                and mapping.fortran_type.upper().lstrip().startswith("LOGICAL")
                and mapping.iso_c_type.startswith("INTEGER")):
            # By reference, so the conversion cannot happen in the call --
            # pass the staging local instead. See _logical_ref_args.
            call_args.append(f"{arg.name}_lgc")
        elif arg.intent in (IntentKind.OUT, IntentKind.INOUT):
            # INOUT/OUT scalars passed by reference (no conversion needed)
            call_args.append(arg.name)
        elif mapping.iso_c_type.startswith("LOGICAL") and mapping.c_kind:
            # LOGICAL needs explicit conversion to C_BOOL
            call_args.append(f"LOGICAL({arg.name}, {mapping.c_kind})")
        elif (mapping.fortran_type.upper().lstrip().startswith("LOGICAL")
                and mapping.iso_c_type.startswith("INTEGER")):
            # type_map.py maps Fortran LOGICAL/LOGICAL(4) to INTEGER(C_INT),
            # which is the right memory layout but is NOT assignment-compatible
            # in Fortran -- passing the LOGICAL straight through is a hard
            # compile error ("passed LOGICAL(4) to INTEGER(4)"). The reverse
            # direction already converts with (/= 0); this is the same
            # conversion going out.
            call_args.append(
                f"MERGE(1_{mapping.c_kind}, 0_{mapping.c_kind}, {arg.name})")
        elif mapping.c_kind != mapping.fortran_kind and mapping.fortran_kind and \
                mapping.byte_size != _fortran_kind_byte_size(mapping.fortran_kind):
            # Need to convert from project kind to C kind (different byte sizes)
            if mapping.iso_c_type.startswith("REAL"):
                call_args.append(f"REAL({arg.name}, {mapping.c_kind})")
            elif mapping.iso_c_type.startswith("INTEGER"):
                call_args.append(f"INT({arg.name}, {mapping.c_kind})")
            else:
                base = mapping.iso_c_type.split("(")[0]
                call_args.append(f"{base}({arg.name}, {mapping.c_kind})")
        else:
            call_args.append(arg.name)

    # Array-valued function results: pass the result variable as the output
    # pointer. CHARACTER results pass a C_CHAR staging buffer instead, since a
    # CHARACTER(n) scalar cannot be sequence-associated with a BIND(C)
    # CHARACTER(KIND=C_CHAR) array dummy.
    if result_is_out_param(sig, kind_aliases, derived_types):
        result_name = sig.result_name or f"{sig.name}_result"
        if result_char_len(sig, kind_aliases, derived_types):
            call_args.append(f"{result_name}_c")
        else:
            call_args.append(result_name)

    return call_args


def _get_use_statements_for_derived_types(sig: FortranSignature) -> list[str]:
    """
    Get USE statements needed for derived type declarations in the wrapper.

    Searches the function's captured USE statements for modules that
    provide the derived types used in the args (both passthrough and
    C-compatible — the wrapper declares all args with original types).
    """
    use_stmts = []
    # Collect derived type names that need USE statements
    derived_type_names = set()
    for arg in sig.args:
        if arg.is_derived_type:
            derived_type_names.add(arg.derived_type_name.upper())

    if not derived_type_names:
        return use_stmts

    # Search the function's USE statements for ones that import these types
    seen_use = set()
    for use_stmt in sig.use_statements:
        use_upper = use_stmt.upper()
        # Skip VIT-generated view module USE statements — _get_view_use_statements handles those
        if "VIT_" in use_upper and "_VIEW" in use_upper:
            continue
        # Check if this USE imports any of our derived types
        for type_name in derived_type_names:
            if type_name in use_upper:
                if use_upper not in seen_use:
                    use_stmts.append(use_stmt)
                    seen_use.add(use_upper)
                break
        else:
            # Also include "USE Module" without ONLY if the module name
            # could plausibly provide the type (heuristic)
            if "ONLY" not in use_upper and "PRECISION" not in use_upper:
                # Don't add generic USE statements unless they match a type pattern
                pass

    return use_stmts


def _format_dims(arg: FortranArg) -> str:
    """Format array dimension spec for Fortran declarations."""
    if arg.array_dims:
        return f"({arg.array_dims})"
    return ""


